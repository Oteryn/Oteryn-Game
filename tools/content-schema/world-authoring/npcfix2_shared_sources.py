"""Restore wiki-qualified Outlaw key contents without replacing personal chest claims.

Source coordinates and key identities are explicit reviewed inputs. Region bytes,
placement counts and capture hashes are always generated by this overlay.
"""
import argparse
import hashlib
import json
from pathlib import Path

import quest_access_bindings as registry
import world_region_codec as codec

ROOT = Path(__file__).resolve().parents[3]
PACKET = 'tools/content-schema/world-authoring/samples/npcfix2-shared-sources.json'
REGION = 'content/world/placements/region-z07-x127-y125.b3'
SPECS = ((32609, 32244, 3301, 2970), (32617, 32250, 3302, 2969), (32651, 32244, 3303, 2970))


def capture(root=ROOT):
    recipes = json.loads((root / 'tools/content-schema/quest-authoring/samples/completion242/recipes.json').read_bytes())
    (quest,) = [r for r in recipes['records'] if r['identity']['key'] == 'oteryn:quest.the_outlaw_camp_quest']
    (source,) = [r for r in quest['recipe']['source_refs'] if r['provider'] == 'tibiawiki_br' and r['revid'] == 428680]
    return {'schema': 'OTERYN_SHARED_SOURCE_LOOT_BINDINGS/v1', 'classification': 'TIBIAWIKI_STRUCTURED',
            'source': source, 'item_source_url': 'https://github.com/zimbadev/crystalserver/blob/201189f871d23597b82caf88fd611454a2ddefb8/data/items/items.xml',
            'bindings': [{'position': [x, y, 7], 'root_item': 3634,
                          'children': [{'item': item, 'key_number': number, 'quantity': 1}]} for x, y, number, item in SPECS]}


def overlay_outputs(outputs, *, require_all=False, packet=None):
    packet = capture() if packet is None else packet
    index = json.loads(outputs[registry.INDEX])
    affected = [row for row in index['regions'] if row['path'] == REGION]
    if not affected:
        if require_all:
            raise ValueError('NPCFIX2_SOURCE_REGION_MISSING')
        return []
    palette = {r['source_item_id']: n for n, r in enumerate(index['palette'])}
    bindings = {tuple(row['position'][:2]): row for row in packet['bindings']}
    imported, inserted = [], 0
    (region,) = affected
    original = outputs[REGION]
    z, rx, ry, sectors = codec.decode_region(original)
    encoded = {}
    for local, tiles in sectors:
        for x, y, flags, house, zones, items in tiles:
            binding = bindings.get((x, y))
            if binding is None:
                continue
            if house or z != binding['position'][2]:
                raise ValueError('NPCFIX2_SOURCE_SCOPE')
            roots = [n for n, (item, depth, _) in enumerate(items)
                     if depth == 0 and item == palette[binding['root_item']]]
            if len(roots) != 1:
                raise ValueError('NPCFIX2_SOURCE_ROOT_AMBIGUOUS')
            (at,) = roots
            if items[at][2]:
                raise ValueError('NPCFIX2_SOURCE_ROOT_BOUND')
            end = at + 1
            while end < len(items) and items[end][1] > 0:
                end += 1
            expected = [(palette[child['item']], 1, {'action': child['key_number']}) for child in binding['children']]
            existing = items[at + 1:end]
            if existing and existing != expected:
                raise ValueError('NPCFIX2_SOURCE_CONTENT_CONFLICT')
            if not existing:
                items[at + 1:at + 1] = expected
                inserted += len(expected)
            imported.append(binding)
        sx, sy = rx * 8 + local % 8, ry * 8 + local // 8
        encoded[local] = codec.encode_sector_tiles(sx, sy, tiles)
    if require_all and len(imported) != len(bindings):
        raise ValueError('NPCFIX2_SOURCE_POSITION_MISSING')
    if not imported:
        return []
    raw = codec.encode_region(z, rx, ry, encoded)
    outputs[REGION] = raw
    region['sha256'] = hashlib.sha256(raw).hexdigest()
    region['items'] += inserted
    index['totals']['items'] += inserted
    packet_raw = registry.canonical(packet)
    index['source']['npcfix2_shared_sources'] = {'path': PACKET, 'sha256': hashlib.sha256(packet_raw).hexdigest(), 'items': len(imported)}
    outputs[registry.INDEX] = registry.canonical(index)
    summary = json.loads(outputs[registry.SUMMARY])
    summary['source'] = index['source']
    summary['totals']['items'] += inserted
    summary['item_attributes']['action'] = summary['item_attributes'].get('action', 0) + inserted
    summary['bytes_on_disk'] += len(raw) - len(original)
    outputs[registry.SUMMARY] = registry.canonical(summary)
    return imported


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--apply', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    raw = registry.canonical(capture())
    packet = ROOT / PACKET
    if args.check:
        if packet.read_bytes() != raw:
            raise SystemExit('NPCFIX2_SOURCE_CAPTURE_DRIFT')
    else:
        packet.write_bytes(raw)
    if args.apply or args.check:
        paths = [registry.INDEX, registry.SUMMARY, REGION]
        outputs = {path: (ROOT / path).read_bytes() for path in paths}
        overlay_outputs(outputs, require_all=True)
        for path, generated in outputs.items():
            if args.check:
                if (ROOT / path).read_bytes() != generated:
                    raise SystemExit('NPCFIX2_SOURCE_OVERLAY_DRIFT:' + path)
            else:
                (ROOT / path).write_bytes(generated)
