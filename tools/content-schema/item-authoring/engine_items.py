def load_wiki_family_fallback(path, identity_index):
    """Strictly parse, validate and resolve the wiki-evidence family fallback snapshot.

    Returns `{item_key: {"profile": family_profile, "matched_names": {lower-cased name,
    ...}, "match_basis": "itemid"|"title"|"appearance_title", "evidence":
    <family_profile_evidence value>}}`. For `match_basis: "appearance_title"`,
    `matched_names` holds the item's own lower-cased appearances.dat name, not its
    items.xml name -- `convert_item` checks the right one against it. Every check here
    is fail-closed, exactly like `load_delivery_overrides`: an unknown top-level or
    record key, a duplicate JSON key, a `snapshot_sha256` that does not match the
    recomputed digest of `records`, a `registry_key` absent from the identity index, a
    missing or unrecognized `match_basis` (must be exactly `itemid`, `title` or
    `appearance_title`), a
    `field`/`value` (or, for a disambiguation, any candidate's `field`/`value`) that the
    admitted mapping does not resolve to exactly one profile, or a profile absent from
    `PROFILE_ITEM_CLASS` (the converter's own admitted family_profile set) is a hard
    error. A missing file is not an error: the fallback is then simply empty, since the
    capture tool is run manually and its snapshot may not exist yet in every checkout.
    """
    if not path.is_file():
        return {}

    def unique_object(pairs):
        keys = [pair_key for pair_key, _value in pairs]
        duplicates = sorted({k for k in keys if keys.count(k) > 1})
        if duplicates:
            raise SystemExit(f"duplicate JSON key(s) in {path}: {duplicates}")
        return dict(pairs)

    try:
        payload = json.loads(
            path.read_text(encoding="utf-8"), object_pairs_hook=unique_object
        )
    except json.JSONDecodeError as exc:
        raise SystemExit(f"invalid JSON in wiki family fallback file {path}: {exc}")

    if not isinstance(payload, dict):
        raise SystemExit(f"wiki family fallback file {path} must be a JSON object")
    allowed_top_keys = {
        "schema",
        "batch_id",
        "family",
        "source",
        "captured_at",
        "records",
        "snapshot_sha256",
    }
    unknown_top = sorted(set(payload) - allowed_top_keys)
    if unknown_top:
        raise SystemExit(f"unknown top-level key(s) in {path}: {unknown_top}")
    missing_top = sorted(allowed_top_keys - set(payload))
    if missing_top:
        raise SystemExit(f"missing required key(s) in {path}: {missing_top}")
    if payload["schema"] != WIKI_FAMILY_FALLBACK_SCHEMA:
        raise SystemExit(
            f"unexpected 'schema' in {path}: {payload['schema']!r} "
            f"(expected {WIKI_FAMILY_FALLBACK_SCHEMA!r})"
        )
    if payload["family"] != "Item":
        raise SystemExit(f"unexpected 'family' in {path}: {payload['family']!r}")

    records = payload["records"]
    if not isinstance(records, dict):
        raise SystemExit(f"'records' in {path} must be a JSON object")
    recomputed = hashlib.sha256(_canonical_records_bytes(records)).hexdigest()
    if recomputed != payload["snapshot_sha256"]:
        raise SystemExit(
            f"snapshot_sha256 mismatch in {path}: recorded "
            f"{payload['snapshot_sha256']!r}, recomputed {recomputed!r}"
        )

    valid_keys = {key for key, _basis in identity_index.values()}
    allowed_record_keys = {
        "registry_key",
        "matched_names",
        "resolution",
        "match_basis",
        "wiki_title",
        "page_id",
        "revision_id",
        "revision_timestamp",
        "url",
        "revision_sha1",
        "content_sha256",
        "captured_at",
        "field",
        "value",
        "candidates",
        "availability_status",
    }
    allowed_candidate_keys = {
        "wiki_title",
        "page_id",
        "revision_id",
        "revision_timestamp",
        "url",
        "revision_sha1",
        "content_sha256",
        "captured_at",
        "field",
        "value",
    }

    def require_str(value, where):
        if not isinstance(value, str) or not value:
            raise SystemExit(f"{where} must be a non-empty string")
        return value

    def require_int(value, where):
        if not isinstance(value, int) or isinstance(value, bool) or value < 1:
            raise SystemExit(f"{where} must be a positive integer")
        return value

    def wiki_source_fields(row, where):
        require_str(row.get("wiki_title"), f"{where}.wiki_title")
        require_int(row.get("page_id"), f"{where}.page_id")
        require_int(row.get("revision_id"), f"{where}.revision_id")
        require_str(row.get("revision_timestamp"), f"{where}.revision_timestamp")
        require_str(row.get("url"), f"{where}.url")
        revision_sha1 = require_str(row.get("revision_sha1"), f"{where}.revision_sha1")
        if len(revision_sha1) != 40:
            raise SystemExit(f"{where}.revision_sha1 must be a 40-char hex SHA-1")
        content_sha256 = require_str(
            row.get("content_sha256"), f"{where}.content_sha256"
        )
        if len(content_sha256) != 64:
            raise SystemExit(f"{where}.content_sha256 must be a 64-char hex SHA-256")
        require_str(row.get("captured_at"), f"{where}.captured_at")

    def resolve_field_value(row, where):
        field = require_str(row.get("field"), f"{where}.field")
        if field not in ("primarytype", "objectclass", "status"):
            raise SystemExit(
                f"{where}.field must be primarytype, objectclass or status"
            )
        value = require_str(row.get("value"), f"{where}.value")
        profile = resolve_wiki_family_value(field, value)
        if profile is None:
            raise SystemExit(
                f"{where}: {field}={value!r} is not in the admitted wiki mapping"
            )
        return profile

    resolved = {}
    for registry_key, record in records.items():
        where = f"{path}:{registry_key}"
        if not isinstance(record, dict):
            raise SystemExit(f"{where}: record must be a JSON object")
        unknown_record = sorted(set(record) - allowed_record_keys)
        if unknown_record:
            raise SystemExit(f"{where}: unknown key(s): {unknown_record}")
        if record.get("registry_key") != registry_key:
            raise SystemExit(f"{where}: 'registry_key' must equal its own map key")
        if registry_key not in valid_keys:
            raise SystemExit(f"{where}: registry_key is not a known Item key")
        matched_names = record.get("matched_names")
        if (
            not isinstance(matched_names, list)
            or not matched_names
            or any(not isinstance(n, str) or not n for n in matched_names)
            or len(set(matched_names)) != len(matched_names)
            or any(n != n.lower() for n in matched_names)
        ):
            raise SystemExit(
                f"{where}: 'matched_names' must be a non-empty list of unique "
                "lower-cased strings"
            )
        resolution = record.get("resolution")
        if resolution not in ("direct", "disambiguation"):
            raise SystemExit(f"{where}: 'resolution' must be direct or disambiguation")
        match_basis = record.get("match_basis")
        if match_basis not in ("itemid", "title", "appearance_title", "actualname"):
            raise SystemExit(
                f"{where}: 'match_basis' must be itemid, title, appearance_title or "
                "actualname"
            )

        if resolution == "direct":
            wiki_source_fields(record, where)
            profile = resolve_field_value(record, where)
            evidence = {
                "resolution": "direct",
                "match_basis": match_basis,
                "field": record["field"],
                "value": record["value"],
                "wiki_source": _wiki_evidence_source_from_record(record),
            }
        else:
            candidates = record.get("candidates")
            if not isinstance(candidates, list) or len(candidates) < 2:
                raise SystemExit(
                    f"{where}: a disambiguation record needs 2+ 'candidates'"
                )
            profiles = set()
            evidence_candidates = []
            for index, candidate in enumerate(candidates):
                cwhere = f"{where}.candidates[{index}]"
                if not isinstance(candidate, dict):
                    raise SystemExit(f"{cwhere}: candidate must be a JSON object")
                unknown_candidate = sorted(set(candidate) - allowed_candidate_keys)
                if unknown_candidate:
                    raise SystemExit(f"{cwhere}: unknown key(s): {unknown_candidate}")
                wiki_source_fields(candidate, cwhere)
                profiles.add(resolve_field_value(candidate, cwhere))
                evidence_candidates.append(
                    {
                        "field": candidate["field"],
                        "value": candidate["value"],
                        "wiki_source": _wiki_evidence_source_from_record(candidate),
                    }
                )
            if len(profiles) != 1:
                raise SystemExit(
                    f"{where}: disambiguation candidates do not all resolve to the "
                    f"same profile: {sorted(profiles)}"
                )
            (profile,) = profiles
            evidence = {
                "resolution": "disambiguation",
                "match_basis": match_basis,
                "candidates": evidence_candidates,
            }

        if profile not in PROFILE_ITEM_CLASS:
            raise SystemExit(
                f"{where}: profile {profile!r} is not an admitted family_profile"
            )

        # Availability (owner decision 2026-09-28, task f): `None` (JSON `null`, or the
        # key simply absent) means the matched page(s) carried no `status` fact at all,
        # or -- for a disambiguation -- the candidates disagreed; never guessed, never
        # defaulted. A present value must be one of `ADMITTED_AVAILABILITY_STATUSES`.
        availability_status = record.get("availability_status")
        if availability_status is None:
            availability = None
        else:
            if (
                not isinstance(availability_status, str)
                or availability_status not in ADMITTED_AVAILABILITY_STATUSES
            ):
                raise SystemExit(
                    f"{where}: 'availability_status' {availability_status!r} is not "
                    "an admitted value"
                )
            evidence_page = record if resolution == "direct" else candidates[0]
            availability = {
                "status": availability_status,
                "evidence": {
                    "source": "tibiawiki",
                    "page_id": evidence_page["page_id"],
                    "revision_id": evidence_page["revision_id"],
                    "wiki_title": evidence_page["wiki_title"],
                    "match_basis": match_basis,
                },
            }

        resolved[registry_key] = {
            "profile": profile,
            "matched_names": set(matched_names),
            "match_basis": match_basis,
            "evidence": evidence,
            "availability": availability,
        }
    return resolved


# --- engine wrap-target family inheritance (owner decision 2026-09-28) --------------
#
# Many `family_profile_unresolved` items are house furniture (chairs, a forge, a
# workbench, lamps) whose own items.xml carries `wrapableto="T"` (almost always the
# generic decoration-kit id 23398, itself `primarytype="furniture"` -> `decoration`).
# This is the lowest-priority family resolution: it only ever runs once every existing
# classifier, `immovable_non_item_route` and the wiki-evidence fallback above have all
# already failed to resolve a family, so no already-resolved item is ever affected by it.
# It is deliberately a single hop: T's own `primarytype` is looked up directly against
# `PRIMARYTYPE_PROFILE`, never through T's own wrapableto (no chaining) and never through
# T's wiki fallback (only an engine attribute this item's own wrap target itself declares
# is trusted). When T does not resolve this way -- absent from items.xml, or its own
# primarytype not admitted -- the item stays unresolved rather than guessed.
def resolve_wrap_target_profile(items, attrs):
    """Return (profile, wrap_target_id, wrap_target_primarytype) from this item's own
    `wrapableto` attribute naming another items.xml id whose own `primarytype` resolves
    through `PRIMARYTYPE_PROFILE`; else `None`."""
    wrap_target_id = to_int(attrs.get("wrapableto"))
    if not wrap_target_id:
        return None
    target_record = items.get(wrap_target_id)
    if target_record is None:
        return None
    target_primarytype = target_record["attrs"].get("primarytype")
    profile = PRIMARYTYPE_PROFILE.get(target_primarytype)
    if profile is None:
        return None
    return profile, wrap_target_id, target_primarytype


# --- corpse-like "dead ..." item routing/profile (owner decision 2026-09-28) --------
#
# An appearance-flagged corpse (`flags.corpse`/`flags.player_corpse`) is already routed
# to WorldObject/corpse by `non_item_route` below, before family classification even
# starts. An engine name starting with "dead " that carries neither flag is either a
# decorative map/quest corpse (never take-able: routed to WorldObject, not an Item at
# all) or a genuinely take-able carcass. This only ever runs once every existing
# classifier, the wrap-target rule above and everything before it have already failed to
# resolve a family, so it never reroutes an already-resolved item. A take-able one is a
# real Item only when its exact lower-cased engine name is in the explicit, reviewed
# owner table below (ordinary animal/creature carcasses -> `material_valuable`; a
# unique/named quest character -> `quest_item`); any other take-able "dead ..." name
# stays unresolved (fail closed) rather than guessed.
DEAD_ITEM_NAME_PREFIX = "dead "
# Exact lower-cased engine name -> family_profile, reviewed by hand against both pinned
# engines' items.xml (every `family_profile_unresolved`, take-able, "dead "-prefixed name)
# 2026-09-28. See docs/agents/tasks/active/OTV2-20260928-item-wrap-target-corpses.md. Every
# name here is an ordinary animal/creature carcass -> `material_valuable`, the same family
# the live creature's other drops carry; none of the take-able names in either pinned
# engine is a unique/named quest character (those, e.g. "dead Doctor Perhaps", "dead
# Dirtbeard", "dead Evil Mastermind", "dead Monstor", "dead Mephiles", all carry no
# `flags.take` and are routed as `corpse_decoration` above instead, never reaching this
# table). An unlisted take-able "dead ..." name stays unresolved (fail closed).
DEAD_CREATURE_PROFILE = {
    "dead troll": "material_valuable",
    "dead rat": "material_valuable",
    "dead snake": "material_valuable",
    "dead spider": "material_valuable",
    "dead wolf": "material_valuable",
    "dead rabbit": "material_valuable",
    "dead frog": "material_valuable",
}


def resolve_dead_item_route_or_profile(name, flags):
    """For an item whose family is still unresolved and whose lower-cased engine `name`
    starts with `DEAD_ITEM_NAME_PREFIX`: return `("route", owner, reason)` for a
    non-take-able decoration corpse, `("profile", family_profile)` for a take-able name
    the owner table admits, or `None` (stays unresolved) when it is take-able but not in
    the table, or when the name does not start with the prefix at all."""
    folded = name.strip().lower()
    if not folded.startswith(DEAD_ITEM_NAME_PREFIX):
        return None
    if not flags.get("flags.take"):
        return ("route", "WorldObject", "corpse_decoration")
    profile = DEAD_CREATURE_PROFILE.get(folded)
    if profile is None:
        return None
    return ("profile", profile)


# --- non-Item routing (corpses, placeholder sprite slots, Terrain/WorldObject types) ---
#
# These items are never candidate Items at all: the pinned catalogs route their deciding
# fields to WorldObject/Terrain/Interaction (`flags.corpse`/`flags.player_corpse`, and the
# `primarytype` values below have no engine attribute correlate other than terrain/fixture
# behavior owned outside Item). An appearance whose engine name is one of the reserved
# placeholder sprite-sheet labels and which carries no other items.xml attribute is a
# sprite-sheet reservation, not a game object. Recognizing these here keeps them out of
# `family_profile_unresolved`/`not_converted`, which would otherwise misreport an owner
# decision the catalogs already made as a converter gap.
CORPSE_FLAGS = ("flags.corpse", "flags.player_corpse")
WORLD_OBJECT_PRIMARYTYPES = {
    "artificial tiles": "Terrain",
    "natural tiles": "Terrain",
    "fields": "Terrain",
    "walls": "Terrain",
    "constructions": "WorldObject",
    "machines (objects)": "WorldObject",
    "machines": "WorldObject",
    "traps": "WorldObject",
}
PLACEHOLDER_APPEARANCE_NAMES = {"reserved sprite", "deprecated item", "empty sprite"}


def non_item_route(xml_record, attrs, flags):
    """Return (owner, reason) when this id names a non-Item owner; else None."""
    if any(flags.get(flag) for flag in CORPSE_FLAGS):
        return "WorldObject", "corpse"
    name = (xml_record.get("name") if xml_record else None) or ""
    if name.strip().lower() in PLACEHOLDER_APPEARANCE_NAMES and not attrs:
        return "WorldObject", "appearance_placeholder_slot"
    primarytype = attrs.get("primarytype")
    if primarytype in WORLD_OBJECT_PRIMARYTYPES:
        return WORLD_OBJECT_PRIMARYTYPES[primarytype], "primarytype_world_object"
    return None


# `flags.unmove` map geometry with no Item family profile (see formal schema §5a): walls
# (`flags.bottom`+`unpass`), ground (`flags.bank`/`fullbank`), borders (`flags.clip`), top
# decorations (`flags.top`), and named doors/stairs/ramps/windows all carry no items.xml
# attribute this converter's family classifiers recognize, because they are immovable map
# geometry owned by WorldObject/Terrain, not an Item family gap. This only applies once
# `classify_family_profile` has already failed to resolve a family: an unmove=true entry
# that does resolve a family (e.g. a heavy, non-pickupable weapon or container) stays a
# converted Item with `physical.movable=false`, exactly as the unmove->movable mapping
# already produces.
GROUND_OR_BORDER_FLAGS = ("flags.bank", "flags.fullbank", "flags.clip")


def immovable_non_item_route(flags):
    """Return (owner, reason) for an unmove=true entry with no resolved family; else None."""
    if not flags.get("flags.unmove"):
        return None
    if any(flags.get(flag) for flag in GROUND_OR_BORDER_FLAGS):
        return "Terrain", "ground_or_border"
    return "WorldObject", "immovable_unclassified"


