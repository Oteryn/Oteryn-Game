def default_artifact_digests(profile, engine):
    digests = dict(ENGINE_ARTIFACT_DIGESTS[profile])
    pool_path = DELIVERY_POOL_PATH[engine]
    digests[pool_path] = (
        DELIVERY_LIST_SHA256 if engine == "crystal" else CANARY_WEEKLY_ITEMS_SHA256
    )
    return digests


def load_engine_sources(
    engine,
    source_root,
    digests=None,
    rule_source=None,
    rule_source_digest=None,
    overrides_path=None,
    wiki_fallback_path=None,
    owner_decisions_path=None,
):
    """digests overrides the pinned production SHA-256 map; used only by fixture tests.

    `rule_source` is the checkout the Delivery Task adoption rule reads its pinned
    Crystal delivery list from. Crystal runs already read that exact file as their own
    pool, so `rule_source` is ignored for `engine == "crystal"`. Canary runs have no
    Crystal checkout of their own: `rule_source` is required, and a missing one is a hard
    error rather than an empty (silently all-ineligible) rule. `rule_source_digest`
    overrides the pinned production SHA-256 for that list; used only by fixture tests.
    `overrides_path` overrides the committed `delivery-task-overrides.json`; used only by
    fixture tests. `wiki_fallback_path` overrides the committed `items-family-fallback.json`
    wiki-evidence snapshot; used only by fixture tests. `owner_decisions_path` overrides
    the committed `owner-item-family-decisions.json`; used only by fixture tests.
    """
    config = ENGINES[engine]
    profile = config["profile"]
    artifact_digests = (
        digests if digests is not None else default_artifact_digests(profile, engine)
    )
    pool_path = DELIVERY_POOL_PATH[engine]

    items_bytes, items_mode = read_verified_artifact(
        source_root, "data/items/items.xml", artifact_digests["data/items/items.xml"]
    )
    appearances_bytes, appearances_mode = read_verified_artifact(
        source_root,
        "data/items/appearances.dat",
        artifact_digests["data/items/appearances.dat"],
    )
    pool_bytes, pool_mode = read_verified_artifact(
        source_root, pool_path, artifact_digests[pool_path]
    )
    delivery_member_ids = DELIVERY_POOL_PARSER[engine](pool_bytes.decode("utf-8"))

    if engine == "crystal":
        # Crystal's own pinned pool file *is* the rule's Crystal delivery list.
        crystal_list_text = pool_bytes.decode("utf-8")
        crystal_list_ids = delivery_member_ids
    else:
        if rule_source is None:
            raise SystemExit(
                "--rule-source <crystal checkout> is required for canary: the "
                f"{RULE_ID!r} Delivery Task rule is keyed by Crystal delivery-list "
                "membership, which canary has no checkout of its own to read."
            )
        expected_digest = (
            rule_source_digest
            if rule_source_digest is not None
            else DELIVERY_LIST_SHA256
        )
        rule_list_bytes, _rule_list_mode = read_verified_artifact(
            Path(rule_source), DELIVERY_LIST_PATH, expected_digest
        )
        crystal_list_text = rule_list_bytes.decode("utf-8")
        crystal_list_ids = parse_crystal_delivery_ids(crystal_list_text)
    crystal_list_entries = len(re.findall(r"itemId\s*=\s*(\d+)", crystal_list_text))

    identity_index = build_identity_index()
    valid_keys = {key for key, _basis in identity_index.values()}
    resolved_overrides_path = (
        overrides_path if overrides_path is not None else DELIVERY_OVERRIDES_PATH
    )
    delivery_overrides = load_delivery_overrides(resolved_overrides_path, valid_keys)
    resolved_wiki_fallback_path = (
        wiki_fallback_path
        if wiki_fallback_path is not None
        else WIKI_FAMILY_FALLBACK_PATH
    )
    wiki_family_fallback = load_wiki_family_fallback(
        resolved_wiki_fallback_path, identity_index
    )
    resolved_owner_decisions_path = (
        owner_decisions_path
        if owner_decisions_path is not None
        else OWNER_FAMILY_DECISIONS_PATH
    )
    owner_family_decisions = load_owner_family_decisions(
        resolved_owner_decisions_path, valid_keys
    )

    return {
        "engine": engine,
        "profile": profile,
        "repository": config["repository"],
        "revision": config["revision"],
        "items": load_items_xml(items_bytes.decode("utf-8")),
        "appearances": load_appearance_objects(appearances_bytes),
        "identity_index": identity_index,
        "delivery_member_ids": delivery_member_ids,
        "delivery_source": DELIVERY_SOURCE_NAME[engine],
        "crystal_list_ids": crystal_list_ids,
        "crystal_list_entries": crystal_list_entries,
        "delivery_overrides": delivery_overrides,
        "wiki_family_fallback": wiki_family_fallback,
        "owner_family_decisions": owner_family_decisions,
        "disposition": load_disposition_catalog(profile),
        "artifact_digests": {
            "data/items/items.xml": {
                "sha256": artifact_digests["data/items/items.xml"],
                "digest_mode": items_mode,
            },
            "data/items/appearances.dat": {
                "sha256": artifact_digests["data/items/appearances.dat"],
                "digest_mode": appearances_mode,
            },
            pool_path: {
                "sha256": artifact_digests[pool_path],
                "digest_mode": pool_mode,
            },
        },
    }


# Dispositions whose status the census counts as automatically routed to another
# owner; never a converter blocker regardless of whether this converter acts on them.
ROUTED_STATUSES = {
    "external_domain",
    "reverse_relation",
    "provenance_only",
    "pinned_no_effect",
    "approved_omission",
}


_NO_VALUE = object()


def route_for_value(disposition_row, raw_value):
    """Return the `source_value_routes` entry pinned for `raw_value`, or None."""
    for route in disposition_row.get("source_value_routes") or ():
        if route.get("source_value") == raw_value:
            return route
    return None


def field_status_row(field, disposition_row, raw_value=_NO_VALUE):
    """(status, blocker_key) for one field. `raw_value` is the value actually observed
    on this item; it is only consulted for a `VALUE_DEPENDENT` disposition, whose own
    top-level `status` is always `unresolved_semantics` regardless of any per-value
    route (the route, not the field, decides mapped/routed/unresolved per Rule 2)."""
    if disposition_row is None:
        return "unsupported", field
    status = disposition_row["status"]
    if status == "mapped":
        return ("mapped" if field in IMPLEMENTED_FIELDS else "converter_missing"), field
    if (
        disposition_row.get("disposition") == "VALUE_DEPENDENT"
        and raw_value is not _NO_VALUE
    ):
        route = route_for_value(disposition_row, raw_value)
        if route is None:
            return "unresolved", f"{field}={raw_value}"
        route_status = route["status"]
        if route_status == "mapped":
            return (
                "mapped" if field in IMPLEMENTED_FIELDS else "converter_missing"
            ), field
        if route_status in ROUTED_STATUSES:
            return "routed", field
        return "unresolved", f"{field}={raw_value}"
    if status == "unresolved_semantics":
        return "unresolved", field
    if status in ROUTED_STATUSES:
        return "routed", field
    return "unsupported", field


HIGH_CONFIDENCE_MATCH_BASES = ("itemid", "title")
NAME_JOINED_MATCH_BASES = ("appearance_title", "actualname")


def fallback_entry_matches_name(fallback_entry, name, appearance, allowed_bases):
    """True when `fallback_entry` (a `load_wiki_family_fallback` entry, or `None`)
    applies to this exact item, and its `match_basis` is one of `allowed_bases`. Wiki
    evidence never applies to an item with no `appearances.dat` object (e.g. the
    fluid-kind name rows 1-20: not a physical Item). Which of this item's own names is
    checked against `matched_names` depends on `match_basis`: `appearance_title` (task
    e) checks only the appearance name; `actualname` (task g) checks either the
    items.xml name or the appearance name (whichever one the capture tool actually
    matched); every other basis (`itemid`, `title`) checks only the items.xml (`name`)
    one.

    `allowed_bases` exists because `itemid`/`title` are exact, authoritative joins
    (an id or an exact engine-name match can never collide with an unrelated wiki
    page), while `appearance_title`/`actualname` are looser, name-string joins that a
    generic engine name (e.g. "dead rat", "dead goblin") can coincidentally share with
    an unrelated page (e.g. a quest-specific variant) that happens to use the same
    literal name. Two already-reviewed, structurally-driven rules -- wrap-target
    inheritance and the dead-item rules -- resolve those generic names correctly from
    engine data alone with no such collision risk, so `convert_item` only consults
    `appearance_title`/`actualname` evidence after both of those have already failed to
    resolve the item, never before (see `convert_item` below)."""
    if fallback_entry is None or appearance is None:
        return False
    basis = fallback_entry.get("match_basis")
    if basis not in allowed_bases:
        return False
    matched = fallback_entry["matched_names"]
    appearance_name = (appearance.get("name") or "").strip().lower()
    if basis == "appearance_title":
        return bool(appearance_name) and appearance_name in matched
    if basis == "actualname":
        return name.strip().lower() in matched or (
            bool(appearance_name) and appearance_name in matched
        )
    return name.strip().lower() in matched


def convert_item(sources, item_id):
    """Return (item, dependencies, report). item/dependencies are None when not_converted."""
    profile = sources["profile"]
    disposition = sources["disposition"]
    identity_index = sources["identity_index"]
    xml_record = sources["items"].get(item_id)
    appearance = sources["appearances"].get(item_id)
    blockers = []
    field_status = {}

    def note(field, present, raw_value=_NO_VALUE):
        if not present:
            return
        status, blocker_key = field_status_row(field, disposition.get(field), raw_value)
        field_status[field] = status
        if status in ("converter_missing", "unresolved", "unsupported"):
            blockers.append(f"{status}:{blocker_key}")

    def demote_to_converter_missing(field):
        """Correct an already-'mapped' field_status for one occurrence whose destination
        this converter could not actually produce (Rule 1: the engine data this specific
        item carries is insufficient, not a general coding gap for the field)."""
        if field_status.get(field) == "mapped":
            field_status[field] = "converter_missing"
            blockers.append(f"converter_missing:{field}")

    identity_entry = identity_index.get(item_id)
    if identity_entry is None:
        # No CW2 B1 allocator key means no Crystal id to check the Delivery Task rule
        # against: the decision stays not admitted rather than being guessed.
        blockers.append("identity_not_in_b1_catalog")
        blockers.append("delivery_task_decision_not_admitted")
        return (
            None,
            None,
            {
                "item_id": item_id,
                "converted": False,
                "blockers": blockers,
                "field_status": field_status,
            },
        )
    key, identity_basis = identity_entry

    attrs = dict(xml_record["attrs"]) if xml_record else {}
    flags = dict(appearance["flags"]) if appearance else {}
    root_fields = ("id", "fromid", "toid", "name", "article", "plural", "editorsuffix")
    for name in disposition:
        if name.startswith("flags.") or "." in name:
            present = name in flags
            note(name, present, flags.get(name) if present else _NO_VALUE)
        elif name not in root_fields:
            present = name in attrs
            note(name, present, attrs.get(name) if present else _NO_VALUE)
    note("name", bool(xml_record and xml_record.get("name")))
    note("article", bool(xml_record and xml_record.get("article")))
    note("plural", bool(xml_record and xml_record.get("plural")))
    note("appearance.id", appearance is not None)
    note("appearance.name", bool(appearance and appearance.get("name")))
    note("appearance.description", bool(appearance and appearance.get("description")))
    note("appearance.frame_group", bool(appearance and appearance.get("frame_groups")))

    non_item = non_item_route(xml_record, attrs, flags)
    if non_item is not None:
        owner, reason = non_item
        return (
            None,
            None,
            {
                "item_id": item_id,
                "key": key,
                "identity_basis": identity_basis,
                "converted": False,
                "routed_non_item": {"owner": owner, "reason": reason},
                "blockers": blockers,
                "field_status": field_status,
            },
        )

    name = (
        (xml_record["name"] if xml_record else None)
        or (appearance.get("name") if appearance else None)
        or f"item {item_id}"
    )
    primarytype = attrs.get("primarytype")
    family_profile = classify_family_profile(
        attrs, primarytype, flags.get("clothes.slot")
    )
    family_profile_basis = None
    family_profile_evidence = None
    availability = None
    if family_profile is None:
        immovable_route = immovable_non_item_route(flags)
        if immovable_route is not None:
            owner, reason = immovable_route
            return (
                None,
                None,
                {
                    "item_id": item_id,
                    "key": key,
                    "identity_basis": identity_basis,
                    "converted": False,
                    "routed_non_item": {"owner": owner, "reason": reason},
                    "blockers": blockers,
                    "field_status": field_status,
                },
            )
        # Engine-attribute classification always wins; the wiki-evidence fallback only
        # ever applies once every engine signal above has already failed to resolve a
        # family, and only when this exact item's own lower-cased name is one the
        # reviewed snapshot actually resolved (else it is ignored and stays unresolved,
        # never guessed from a same-named-but-different item's evidence). An entry with
        # no `appearances.dat` object (e.g. the fluid-kind name rows 1-20) is not a
        # physical Item, so wiki evidence about a same-named object never applies to it.
        #
        # Only the exact, authoritative `itemid`/`title` bases are consulted here. The
        # looser name-joined bases (`appearance_title` task e, `actualname` task g) are
        # consulted further below, only once wrap-target inheritance and the dead-item
        # rules have both already failed -- see `fallback_entry_matches_name`'s
        # docstring for why (generic engine names can collide with an unrelated wiki
        # page's `actualname`, but wrap-target/dead-item already resolve those generic
        # names correctly from engine data alone).
        fallback_entry = sources.get("wiki_family_fallback", {}).get(key)
        if fallback_entry_matches_name(
            fallback_entry, name, appearance, HIGH_CONFIDENCE_MATCH_BASES
        ):
            family_profile = fallback_entry["profile"]
            family_profile_basis = "wiki_evidence_fallback"
            family_profile_evidence = fallback_entry["evidence"]
            availability = fallback_entry.get("availability")
        else:
            # `sources["skip_post_wiki_fallback_routes"]`: set only by
            # `item_wiki_family_capture.collect_unresolved`'s wiki-OFF probe, which asks
            # "does this id need a wiki lookup at all". EVERY rule below this point --
            # wrap-target inheritance, the dead-item rules, and the three last-resort
            # non-Item routes further down -- is LOWER priority than the wiki fallback
            # above (real wiki evidence, once it exists, always wins over any of them).
            # Letting one of them fire in that probe would wrongly mark an id "already
            # handled" and permanently exclude it from the wiki lookup, silently dropping
            # its real, still-current wiki evidence from every future recapture and then
            # falling through to the wrong (or merely differently-sourced) answer in
            # production. The flag is never set for a real conversion.
            skip_post_wiki = sources.get("skip_post_wiki_fallback_routes", False)
            wrap_target = (
                None
                if skip_post_wiki
                else resolve_wrap_target_profile(sources["items"], attrs)
            )
            if wrap_target is not None:
                wrap_profile, wrap_target_id, wrap_target_primarytype = wrap_target
                family_profile = wrap_profile
                family_profile_basis = "engine_wrap_target"
                family_profile_evidence = {
                    "wrap_target_id": wrap_target_id,
                    "wrap_target_primarytype": wrap_target_primarytype,
                }
            elif not skip_post_wiki:
                dead_route = resolve_dead_item_route_or_profile(name, flags)
                if dead_route is not None and dead_route[0] == "route":
                    _kind, owner, reason = dead_route
                    return (
                        None,
                        None,
                        {
                            "item_id": item_id,
                            "key": key,
                            "identity_basis": identity_basis,
                            "converted": False,
                            "routed_non_item": {"owner": owner, "reason": reason},
                            "blockers": blockers,
                            "field_status": field_status,
                        },
                    )
                if dead_route is not None and dead_route[0] == "profile":
                    family_profile = dead_route[1]
                    family_profile_basis = "owner_name_rule"
                    family_profile_evidence = {
                        "rule": "take_able_dead_creature",
                        "name": name.strip().lower(),
                    }
            # Name-joined wiki evidence (`appearance_title` task e, `actualname` task g),
            # consulted only now that wrap-target inheritance and the dead-item rules
            # have both already failed. See `fallback_entry_matches_name`'s docstring:
            # this ordering exists so that a generic engine name already resolved
            # correctly by one of those two structural rules is never overridden by a
            # same-named-but-unrelated wiki page reached only through a looser name join.
            if (
                family_profile is None
                and not skip_post_wiki
                and fallback_entry_matches_name(
                    fallback_entry, name, appearance, NAME_JOINED_MATCH_BASES
                )
            ):
                family_profile = fallback_entry["profile"]
                family_profile_basis = "wiki_evidence_fallback"
                family_profile_evidence = fallback_entry["evidence"]
                availability = fallback_entry.get("availability")
            # Owner-reviewed leftover-family decision table (task #15, 2026-09-28): the
            # LAST classifier, consulted only once every rule above -- engine
            # attributes, both wiki-evidence tiers, wrap-target inheritance and the
            # dead-item rules -- has already failed to resolve this exact item. Gated by
            # `skip_post_wiki` the same way as every other post-wiki-fallback rule (a
            # per-item owner decision still ranks below the wiki fallback for the
            # capture tool's probe). The item's own lower-cased name must equal the
            # decision's own `name` guard, exactly like the dead-item owner table above.
            if (
                family_profile is None
                and not skip_post_wiki
                and (
                    owner_decision := sources.get("owner_family_decisions", {}).get(key)
                )
                is not None
                and name.strip().lower() == owner_decision["name"]
            ):
                family_profile = owner_decision["profile"]
                family_profile_basis = "owner_name_rule"
                family_profile_evidence = {
                    "rule": "owner_leftover_review_2026_09_28",
                    "name": owner_decision["name"],
                }
            if family_profile is None:
                # Last-resort non-Item routing rules (owner decision 2026-09-28). Each
                # only ever runs once every classifier above -- engine attributes, the
                # wiki-evidence fallback (both priority tiers), wrap-target inheritance,
                # the dead-item rules and the owner leftover-family table -- has already
                # failed to resolve this exact item, so none can ever reroute an
                # already-resolved or already-routed id. See
                # `skip_post_wiki_fallback_routes` above: gated the same way.
                if not skip_post_wiki:
                    fluid_route = resolve_fluid_type_route(name, xml_record, appearance)
                    if fluid_route is not None:
                        owner, reason = fluid_route
                        return (
                            None,
                            None,
                            {
                                "item_id": item_id,
                                "key": key,
                                "identity_basis": identity_basis,
                                "converted": False,
                                "routed_non_item": {"owner": owner, "reason": reason},
                                "blockers": blockers,
                                "field_status": field_status,
                            },
                        )
                    late_placeholder_route = resolve_late_placeholder_route(name)
                    if late_placeholder_route is not None:
                        owner, reason = late_placeholder_route
                        return (
                            None,
                            None,
                            {
                                "item_id": item_id,
                                "key": key,
                                "identity_basis": identity_basis,
                                "converted": False,
                                "routed_non_item": {"owner": owner, "reason": reason},
                                "blockers": blockers,
                                "field_status": field_status,
                            },
                        )
                    no_appearance_route = resolve_no_client_appearance_route(appearance)
                    if no_appearance_route is not None:
                        owner, reason = no_appearance_route
                        return (
                            None,
                            None,
                            {
                                "item_id": item_id,
                                "key": key,
                                "identity_basis": identity_basis,
                                "converted": False,
                                "routed_non_item": {"owner": owner, "reason": reason},
                                "blockers": blockers,
                                "field_status": field_status,
                            },
                        )
                    empty_object_route = resolve_empty_client_object_route(appearance)
                    if empty_object_route is not None:
                        owner, reason = empty_object_route
                        return (
                            None,
                            None,
                            {
                                "item_id": item_id,
                                "key": key,
                                "identity_basis": identity_basis,
                                "converted": False,
                                "routed_non_item": {"owner": owner, "reason": reason},
                                "blockers": blockers,
                                "field_status": field_status,
                            },
                        )
                blockers.append("family_profile_unresolved")
                return (
                    None,
                    None,
                    {
                        "item_id": item_id,
                        "key": key,
                        "identity_basis": identity_basis,
                        "converted": False,
                        "blockers": blockers,
                        "field_status": field_status,
                    },
                )

    item = {
        "identity": {"key": key, "revision": DEFINITION_REVISION},
        "display_name": name,
        "family_profile": family_profile,
        "taxonomy": {
            "item_class": PROFILE_ITEM_CLASS[family_profile],
            "primary": primarytype or attrs.get("weapontype") or family_profile,
        },
    }
    if family_profile_basis is not None:
        item["family_profile_basis"] = family_profile_basis
        item["family_profile_evidence"] = family_profile_evidence
    # Owner decision 2026-09-28 (task f): present only when the wiki-evidence fallback
    # decided this Item's family_profile AND the matched page(s) carried a `status`
    # fact. Absence means "not asserted", never "available" -- an Item with no wiki
    # record, or one resolved some other way, never carries this field at all.
    if availability is not None:
        item["availability"] = availability
    # `RULE_ID`: eligible iff the Crystal id sharing this Item's allocator key is a
    # member of the pinned Crystal delivery list, unless a per-item override applies.
    # This engine's own pool membership is kept as observation only; it never decides.
    is_pool_member = item_id in sources["delivery_member_ids"]
    override = sources["delivery_overrides"].get(key)
    if override is not None:
        decision = {
            "rule": RULE_ID,
            "basis": "override",
            "eligible": override["eligible"],
            "reason": override["reason"],
        }
    else:
        crystal_list_member = item_id in sources["crystal_list_ids"]
        decision = {
            "rule": RULE_ID,
            "basis": (
                "crystal_list_member"
                if crystal_list_member
                else "crystal_list_non_member"
            ),
            "eligible": crystal_list_member,
        }
    delivery_task_report = {
        "observation": {"source": sources["delivery_source"], "member": is_pool_member},
        "decision": decision,
    }
    item["delivery_task_eligible"] = decision["eligible"]

    dependencies = {
        "definitions": [],
        "assets": [],
        "presentations": [],
        "proficiency_crosswalks": [],
    }
    definitions = {}

    def add_item_ref(target_id):
        ref = item_ref(identity_index, target_id)
        if ref is None or ref["key"] == key:
            # A self-reference (e.g. a decayto/transform cycle back to itself) is not
            # a valid dependency edge; the caller treats a None return as "no target".
            return None
        definitions[ref["key"]] = ref
        return ref

    # type: source_value_routes exact-value taxonomy override (Rule 2). Values not
    # covered by a route are `unresolved:type=<value>`, or automatically routed when
    # the matched route's own status is external_domain (a WorldObject/Terrain type
    # value the taxonomy field itself never claims).
    type_route = route_for_value(disposition.get("type") or {}, attrs.get("type"))
    if (
        type_route
        and type_route["status"] == "mapped"
        and "destination_value_equals" in type_route
    ):
        item["taxonomy"]["item_class"] = type_route["destination_value_equals"]

    # loottype: a free-text engine loot-source label; slugged into the tags namespace
    # (tags need no "ns:local" prefix, unlike most other keys in this schema).
    if "loottype" in attrs:
        tag = re.sub(r"[^a-z0-9_.-]+", "_", attrs["loottype"].strip().lower()).strip(
            "_"
        )
        if tag and re.match(r"^[a-z][a-z0-9_.-]*$", tag):
            tags = item["taxonomy"].setdefault("tags", [])
            if tag not in tags:
                tags.append(tag)
        else:
            demote_to_converter_missing("loottype")

    # physical
    physical = {}
    if "weight" in attrs:
        destination, payload = weight_payload(to_int(attrs["weight"]))
        if destination == "weight":
            physical["weight"] = payload
        else:
            item.setdefault("presentation", {})["display_weight"] = payload
    # flags.unmove: VALUE_DEPENDENT, both source_value_routes (true and false) map to
    # /item/physical/movable via `boolean_not_source` (movable = not unmove); an explicit
    # engine-level immovable fact wins over the xml `movable` attribute when both are
    # present, since unmove is the more specific, appearance-level fact.
    if "movable" in attrs:
        physical["movable"] = truthy(attrs["movable"])
    if "flags.unmove" in flags:
        movable_from_unmove = not flags["flags.unmove"]
        physical["movable"] = physical.get("movable", True) and movable_from_unmove
    if "pickupable" in attrs or "allowpickupable" in attrs or flags.get("flags.take"):
        physical["pickupable"] = truthy(
            attrs.get("pickupable", attrs.get("allowpickupable", "1"))
        ) or bool(flags.get("flags.take"))
    if physical:
        item["physical"] = physical

    # presentation
    presentation = item.get("presentation", {})
    grammar = {}
    if xml_record and xml_record.get("article"):
        grammar["article"] = xml_record["article"]
    if xml_record and xml_record.get("plural"):
        grammar["plural"] = xml_record["plural"]
    if grammar:
        presentation["grammar"] = grammar
    description = attrs.get("description") or (
        appearance.get("description") if appearance else None
    )
    if description:
        presentation["inspection_description"] = description
    if appearance is not None and appearance.get("frame_groups"):
        presentation["appearance_binding"] = presentation_ref(profile, item_id)
        dependencies["presentations"].append(
            build_presentation_dependency(profile, item_id, appearance)
        )
        blockers.append("sprite_atlas_not_admitted")
    # display_flags: client-side HUD toggles with no gameplay effect of their own; each
    # is a plain boolean fact from whichever engine surface carries it (appearance flag
    # or xml attribute), so several source fields can and do corroborate the same leaf.
    display_flags = {}
    if (
        flags.get("flags.expire") is not None
        or flags.get("flags.expirestop") is not None
        or flags.get("flags.clockexpire") is not None
    ):
        display_flags["client_expiry_timer"] = bool(
            flags.get("flags.expire")
            or flags.get("flags.expirestop")
            or flags.get("flags.clockexpire")
        )
    if flags.get("flags.wearout") is not None:
        display_flags["client_wear_counter"] = bool(flags["flags.wearout"])
    if "showcount" in attrs:
        display_flags["stack_count"] = truthy(attrs["showcount"])
    if "showattributes" in attrs:
        display_flags["attributes"] = truthy(attrs["showattributes"])
    if "showduration" in attrs:
        display_flags["duration"] = truthy(attrs["showduration"])
    if display_flags:
        presentation["display_flags"] = display_flags
    # effects/projectile_effect/attack_effect: asset-bound identifiers, registered into
    # dependencies["assets"] the same way the existing light color_binding is, so the
    # validator's asset-resolution pass can confirm every reference used is declared.
    engine = sources["engine"]
    if "effect" in attrs:
        asset_key = f"{engine}.appearance:effect/{attrs['effect']}"
        dependencies["assets"].append(asset_key)
        presentation["effects"] = [asset_key]
    if "shoottype" in attrs:
        asset_key = f"{engine}.appearance:projectile/{attrs['shoottype']}"
        dependencies["assets"].append(asset_key)
        presentation["projectile_effect"] = asset_key
    if "meleeattackeffect" in attrs:
        asset_key = (
            f"{engine}.appearance:melee-attack-effect/{attrs['meleeattackeffect']}"
        )
        dependencies["assets"].append(asset_key)
        presentation["attack_effect"] = asset_key
    if presentation:
        item["presentation"] = presentation

    # equipment
    equipment = build_equipment(attrs, flags.get("clothes.slot"))
    quiver_container = family_profile == "container_equipment"
    # eventtype: only "equip"/"deequip" are mapped (to activation events "equip"/
    # "unequip"); the other routed values (stepin/stepout/additem/removeitem) are
    # external_domain and need no Item-side application. The destination is an
    # equipment activation event, so it can only be applied when `equipment` itself was
    # built (compact slot/hands form); an eventtype on an item with no resolvable slot
    # is the one case this converter cannot represent and stays a precise blocker.
    eventtype_route = route_for_value(
        disposition.get("eventtype") or {}, attrs.get("eventtype")
    )
    eventtype_event = (
        eventtype_route.get("destination_array_contains")
        if eventtype_route and eventtype_route["status"] == "mapped"
        else None
    )
    if equipment:
        if flags.get("flags.dual_wielding"):
            equipment["dual_wielding"] = True
        if eventtype_event:
            equipment["activation_events"] = [eventtype_event]
        item["equipment"] = equipment
    elif eventtype_event:
        demote_to_converter_missing("eventtype")

    # weapon
    # weapontype: VALUE_DEPENDENT; weapon_type is taken from the catalog's own
    # `destination_value_equals` for the matched route (never a static local table).
    # "ammo" and "rod" are pinned no-effect (neither is a key in the engine's own
    # `WeaponTypesMap`; the engine logs "Unknown weaponType" and leaves weaponType at
    # WEAPON_NONE), so they never produce a `weapon_type` even though `WEAPON_TYPE_PROFILE`
    # above still classifies the family. A raw value with no route at all stays an
    # `unresolved:weapontype=<value>` blocker instead of silently passing through.
    weapon_type_raw = attrs.get("weapontype")
    weapon_type_route = route_for_value(
        disposition.get("weapontype") or {}, weapon_type_raw
    )
    weapon_type_value = (
        weapon_type_route["destination_value_equals"]
        if weapon_type_route and weapon_type_route["status"] == "mapped"
        else None
    )
    build_weapon = weapon_type_value is not None or family_profile == "weapon_melee"
    if build_weapon:
        weapon = {"weapon_type": weapon_type_value or "sword"}
        for field, dest in (
            ("attack", "attack"),
            ("defense", "defense"),
            ("extradef", "extra_defense"),
            ("range", "range_cells"),
        ):
            if field in attrs:
                weapon[dest] = to_int(attrs[field])
        if "ammotype" in attrs:
            weapon["ammunition_kind"] = attrs["ammotype"]
        if "hitchance" in attrs:
            weapon["hit_chance_modifier_percent"] = ratio_value(
                to_int(attrs["hitchance"])
            )
        if "maxhitchance" in attrs:
            weapon["max_hit_chance_percent"] = ratio_value(
                to_int(attrs["maxhitchance"])
            )
        if "breakchance" in attrs:
            weapon["break_chance_percent"] = ratio_value(to_int(attrs["breakchance"]))
        if "fromdamage" in attrs and "todamage" in attrs:
            low, high = to_int(attrs["fromdamage"]), to_int(attrs["todamage"])
            weapon["damage_range"] = {
                "minimum": min(low, high),
                "maximum": max(low, high),
            }
        if attrs.get("wandtype") in (
            "physical",
            "energy",
            "earth",
            "fire",
            "life_drain",
            "mana_drain",
            "drowning",
            "ice",
            "holy",
            "death",
            "agony",
            "neutral",
            "healing",
        ):
            weapon["damage_type"] = attrs["wandtype"]
        elemental_attack = [
            {"damage_type": damage_type, "amount": to_int(attrs[field])}
            for field, damage_type in ELEMENTAL_ATTACK_SUFFIX_MAP.items()
            if field in attrs
        ]
        if elemental_attack:
            weapon["elemental_attack"] = elemental_attack
        # action: VALUE_DEPENDENT, each mapped route pins an exact consumption_mode.
        action_route = route_for_value(
            disposition.get("action") or {}, attrs.get("action")
        )
        if (
            action_route
            and action_route["status"] == "mapped"
            and "destination_value_equals" in action_route
        ):
            weapon["consumption_mode"] = action_route["destination_value_equals"]
        # chain: a nested-script coefficient (e.g. "0.9"); absent means "inherit engine
        # defaults" per the schema, so it is only ever applied when present.
        if "chain" in attrs:
            try:
                coefficient = Fraction(str(attrs["chain"]).strip())
            except (ValueError, ZeroDivisionError):
                coefficient = None
            if coefficient and coefficient > 0:
                weapon["chain"] = {
                    "mode": "override",
                    "skill_formula_coefficient": {
                        "numerator": coefficient.numerator,
                        "denominator": coefficient.denominator,
                    },
                }
            else:
                demote_to_converter_missing("chain")
        item["weapon"] = weapon
    else:
        if "action" in attrs:
            action_route = route_for_value(
                disposition.get("action") or {}, attrs.get("action")
            )
            if action_route and action_route["status"] == "mapped":
                demote_to_converter_missing("action")
        if "chain" in attrs:
            demote_to_converter_missing("chain")

    # protection
    protection = {}
    if "armor" in attrs:
        protection["armor"] = to_int(attrs["armor"])
    resistances = build_resistances(attrs)
    if resistances:
        protection["resistances"] = resistances
    suppressions = build_condition_suppressions(attrs)
    if suppressions:
        protection["condition_suppressions"] = suppressions
    if protection:
        item["protection"] = protection

    # container
    if "containersize" in attrs:
        content_kind = "items"
        if quiver_container:
            content_kind = "ammunition"
        elif primarytype == "fluid containers":
            content_kind = "fluids"
        item["container"] = {
            "capacity": to_int(attrs["containersize"]),
            "content_kind": content_kind,
        }
    elif flags.get("flags.container"):
        # The appearance says this is a container, but no `containersize` attribute
        # gives the required capacity; /item/container has no admitted default (unlike
        # stack/max_count), so this occurrence stays a precise blocker rather than an
        # invented capacity.
        demote_to_converter_missing("flags.container")

    # stack: flags.cumulative is VALUE_DEPENDENT-shaped in practice (present == true in
    # both pinned engines) but the field itself is a plain boolean fact; max_count has no
    # per-item source (neither engine's items.xml ever sets `stacksize`) so it takes the
    # admitted engine-default normalization already encoded in validate_item.py's
    # non-source-default rule: stackable -> 100, not stackable -> 1.
    if "flags.cumulative" in flags:
        stackable = bool(flags["flags.cumulative"])
        item["stack"] = {
            "stackable": stackable,
            "max_count": 100 if stackable else 1,
        }

    # charges
    if "charges" in attrs:
        charges = {"count": max(1, to_int(attrs["charges"], 1))}
        if "showcharges" in attrs:
            charges["show_count"] = truthy(attrs["showcharges"])
        item["charges"] = charges

    # temporal + lifecycle transforms/wrapping
    decay_target_id = to_int(attrs.get("decayto", 0))
    if "decayto" in attrs and "duration" in attrs:
        temporal = {
            "duration_ms": max(1, to_int(attrs["duration"]) * 1000),
            "consumption_mode": "continuous",
        }
        if decay_target_id:
            ref = add_item_ref(decay_target_id)
            if ref:
                temporal["decay_target"] = ref
        if "stopduration" in attrs:
            temporal["stop_duration_while_unequipped"] = truthy(attrs["stopduration"])
        item["temporal"] = temporal
    elif "stopduration" in attrs:
        # stop_duration_while_unequipped lives on /item/temporal, which requires
        # duration_ms + consumption_mode; almost every pinned occurrence lacks a
        # decayto/duration pair to build that object from, so this stays a precise
        # blocker rather than fabricating a temporal object with no source duration.
        demote_to_converter_missing("stopduration")
    transforms = []
    for field, trigger in (
        ("destroyto", "destroy"),
        ("transformequipto", "equip"),
        ("transformdeequipto", "unequip"),
        ("transformonuse", "use"),
    ):
        target_id = to_int(attrs.get(field, 0))
        if field in attrs and target_id:
            ref = add_item_ref(target_id)
            if ref:
                transforms.append({"trigger": trigger, "target": ref})
    if decay_target_id and "decayto" in attrs:
        ref = add_item_ref(decay_target_id)
        if ref:
            transforms.append({"trigger": "decay", "target": ref})
    # changedtoexpire/former_object_typeid: an appearance-level alternate source for the
    # same decay fact as decayto/duration. In both pinned engines every occurrence but
    # one already carries a matching decayto (verified against former_object_typeid), so
    # it corroborates the already-built decay transform; former_object_typeid alone
    # cannot build /item/temporal (which also requires a source duration this appearance
    # flag does not carry), so a genuine mismatch stays a precise blocker.
    if flags.get("flags.changedtoexpire"):
        former_target_id = to_int(flags.get("changedtoexpire.former_object_typeid", 0))
        decay_trigger_target = next(
            (t["target"] for t in transforms if t["trigger"] == "decay"), None
        )
        corroborated = (
            former_target_id
            and decay_trigger_target is not None
            and item_ref(identity_index, former_target_id) is not None
            and decay_trigger_target["key"]
            == item_ref(identity_index, former_target_id)["key"]
        )
        if not corroborated:
            demote_to_converter_missing("flags.changedtoexpire")
            demote_to_converter_missing("changedtoexpire.former_object_typeid")
    wrapping = {}
    if flags.get("flags.wrap"):
        wrapping["wrap_enabled"] = True
    if flags.get("flags.unwrap"):
        wrapping["unwrap_enabled"] = True
    if flags.get("flags.wrapkit"):
        wrapping["is_wrap_kit"] = True
    if "wrapableto" in attrs and to_int(attrs["wrapableto"]):
        ref = add_item_ref(to_int(attrs["wrapableto"]))
        if ref:
            wrapping["wrap_target"] = ref
    if "wrapcontainer" in attrs:
        wrapping["preserve_contents"] = truthy(attrs["wrapcontainer"])
    lifecycle = {}
    if transforms:
        lifecycle["transforms"] = transforms
    if wrapping:
        lifecycle["wrapping"] = wrapping
    if lifecycle:
        item["lifecycle"] = lifecycle

    # imbuement
    if "imbuementslot" in attrs:
        item["imbuement"] = {"slot_count": to_int(attrs["imbuementslot"])}

    # fluid: flags.liquidcontainer marks the item itself as the vessel that holds a
    # fluid (schema role "container"), distinct from role "content" (a poured-out fluid
    # unit, which this converter has no source field for).
    if flags.get("flags.liquidcontainer"):
        item["fluid"] = {"role": "container"}

    # forge: flags.upgradeclassification marks the item as forge-upgradeable; the
    # classification level itself is upgradeclassification.upgrade_classification.
    # max_tier is not a source fact: it is the highest tier key
    # `data/scripts/systems/item_tiers.lua` registers for that classification (see
    # `FORGE_CLASSIFICATION_MAX_TIER`'s comment in source_field_catalogs.py), so this
    # converter only emits /item/forge for one of the four classifications that table
    # registers.
    if flags.get("flags.upgradeclassification"):
        classification = to_int(
            flags.get("upgradeclassification.upgrade_classification", 0)
        )
        max_tier = FORGE_CLASSIFICATION_MAX_TIER.get(classification)
        if max_tier is not None:
            item["forge"] = {"classification": classification, "max_tier": max_tier}
        else:
            demote_to_converter_missing("flags.upgradeclassification")
            demote_to_converter_missing("upgradeclassification.upgrade_classification")

    # light
    if flags.get("flags.light"):
        brightness = to_int(flags.get("light.brightness", 0))
        if brightness:
            color = to_int(flags.get("light.color", 0))
            asset_key = f"{sources['engine']}.appearance:light-color/{color}"
            dependencies["assets"].append(asset_key)
            item["light"] = {
                "emits": True,
                "color_binding": asset_key,
                "intensity": brightness,
            }

    # requirements / trade
    requirements = {}
    min_level = to_int(attrs.get("level", flags.get("market.minimum_level", 0)))
    if min_level:
        requirements["min_level"] = min_level
    if "premium" in attrs:
        requirements["premium_only"] = truthy(attrs["premium"])
    # unproperly: every pinned occurrence in both engines is "true" (a weapon usable
    # below its level/vocation requirement at a fixed damage penalty); the schema's
    # `level_magic_shortfall` policy has exactly one admitted shape for this.
    if truthy(attrs.get("unproperly", "0")):
        requirements["level_magic_shortfall"] = {
            "policy": "allow_with_multiplicative_damage_penalty",
            "damage_multiplier_per_failed_check": {"numerator": 1, "denominator": 2},
        }
    professions = flags.get("market.restrict_to_profession")
    vocations = (
        sorted(
            {PLAYER_PROFESSION_NAMES.get(p, str(p)) for p in professions}
            - {"any", "none"}
        )
        if professions
        else []
    )
    if "vocation" in attrs:
        parsed = parse_vocation_attribute(attrs["vocation"])
        if parsed:
            vocations = sorted(parsed)
    on_equip_profiles = (
        "weapon_melee",
        "weapon_distance",
        "equipment_armor",
        "equipment_offhand",
        "container_equipment",
    )
    if requirements or vocations or family_profile in ("weapon_magic", "rune"):
        requirements["enforcement_mode"] = (
            "on_equip" if family_profile in on_equip_profiles else "on_use"
        )
        if vocations:
            requirements["vocations"] = vocations
        item["requirements"] = requirements
    trade = {}
    if flags.get("flags.market"):
        category = flags.get("market.category")
        if category is not None:
            trade["marketable"] = True
            if category in ITEM_CATEGORY_NAMES:
                trade["market_category"] = ITEM_CATEGORY_NAMES[category]
            if vocations:
                trade["vocations"] = vocations
    if trade:
        item["trade"] = trade

    # readable
    # flags.write/flags.write_once are an appearance-level alternate source of
    # readability only: both engines' items.cpp set canReadText from
    # has_write()/has_write_once() presence alone, then immediately discard the nested
    # max_text_length(_once) value on the very next line. Writability, write policy, the
    # write-once target and the actual max character count come only from the XML
    # writeable/maxtextlen/writeonceitemid attributes (ItemParse::parseWriteables); the
    # engine's Game::playerWriteItem only ever transforms an item when the XML-derived
    # writeOnceItemId != 0.
    has_write_flag = bool(flags.get("flags.write") or flags.get("flags.write_once"))
    if "readable" in attrs or "writeable" in attrs or has_write_flag:
        readable = {"readable": True}
        writable = truthy(attrs.get("writeable", "0"))
        readable["writable"] = writable
        max_len = to_int(attrs.get("maxtextlen", 0))
        wants_write_once = "writeonceitemid" in attrs
        write_once_ref = (
            add_item_ref(to_int(attrs["writeonceitemid"]))
            if "writeonceitemid" in attrs
            else None
        )
        if (
            writable
            and max_len > 0
            and (not wants_write_once or write_once_ref is not None)
        ):
            readable["write_policy"] = "write_once" if wants_write_once else "rewrite"
            readable["max_characters"] = max_len
            if wants_write_once:
                readable["write_once_target"] = write_once_ref
        elif writable:
            # write_policy write_once requires write_once_target (schema); an
            # unresolvable writeonceitemid target leaves this converter with none to
            # point at, and a missing/zero XML maxtextlen leaves no max_characters to
            # report; write_policy rewrite would misrepresent either case as freely
            # rewritable, so this occurrence downgrades to non-writable rather than
            # guessing either shape.
            if wants_write_once and write_once_ref is None:
                demote_to_converter_missing("writeonceitemid")
            if max_len <= 0:
                demote_to_converter_missing("writeable")
            writable = False
            readable["writable"] = False
            readable["write_policy"] = "none"
        else:
            readable["write_policy"] = "none"
        if "allowdistread" in attrs:
            readable["distance_readable"] = truthy(attrs["allowdistread"])
        item["readable"] = readable

    # use
    use = {}
    if flags.get("flags.usable") or flags.get("flags.default_action"):
        use["usable"] = True
    if flags.get("flags.multiuse"):
        use["use_with"] = True
    if use:
        use.setdefault("usable", False)
        use.setdefault("use_with", False)
        if "mana" in attrs:
            use["mana_cost"] = to_int(attrs["mana"])
        action = flags.get("default_action.action")
        if action in PLAYER_ACTION_NAMES and PLAYER_ACTION_NAMES[action] != "none":
            use["default_action"] = PLAYER_ACTION_NAMES[action]
        item["use"] = use

    # modifiers
    modifiers = build_modifiers(attrs)
    if modifiers:
        item["modifiers"] = modifiers
    if "elementalbond" in attrs and attrs["elementalbond"] not in (
        "physical",
        "energy",
        "earth",
    ):
        # Every value observed in both pinned engines is within the schema's restricted
        # enum; a value outside it has no admitted damage_type and stays a blocker.
        demote_to_converter_missing("elementalbond")

    # proficiency: a numeric source proficiency id maps only through an admitted exact
    # crosswalk (Rule 1/`proficiency_profiles`). `validate_item.py` requires *both* the
    # Canary and Crystal source identities to corroborate the same target ("exact Canary
    # and Crystal source corroboration is required"), but that admitted pair is pinned
    # and vetted out of band in `proficiency_profiles.py`, not derived from this run's own
    # engine evidence, so a single-engine converter run can still cite both entries for
    # the one id/version they admit (Magic Sword, 238). Every other id has no admitted
    # crosswalk at all and stays a precise blocker.
    proficiency_id = flags.get("proficiency.proficiency_id")
    if proficiency_id is not None:
        if str(proficiency_id) in ADMITTED_PROFICIENCY_EXTERNAL_IDS:
            item["proficiency"] = magic_sword_proficiency()
            dependencies["proficiency_crosswalks"].append(
                proficiency_crosswalk(CANARY_PROFICIENCY_SOURCE)
            )
            dependencies["proficiency_crosswalks"].append(
                proficiency_crosswalk(CRYSTAL_PROFICIENCY_SOURCE)
            )
            for ref in (
                MAGIC_SWORD_PROFICIENCY_REF,
                INTENSE_WOUND_CLEANSING_REF,
                BERSERK_REF,
            ):
                definitions[ref["key"]] = ref
        else:
            demote_to_converter_missing("proficiency.proficiency_id")
            blockers.append(f"proficiency_crosswalk_not_admitted:{proficiency_id}")

    if definitions:
        dependencies["definitions"] = [definitions[k] for k in sorted(definitions)]

    report_family_profile_basis = (
        {"family_profile_basis": family_profile_basis}
        if family_profile_basis is not None
        else {}
    )
    return (
        item,
        dependencies,
        {
            "item_id": item_id,
            "key": key,
            "identity_basis": identity_basis,
            "family_profile": family_profile,
            **report_family_profile_basis,
            "delivery_task": delivery_task_report,
            "converted": True,
            "blockers": blockers,
            "field_status": field_status,
        },
    )


