"""Compile the Observer Eye movement selectors from qualified World placements."""

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tools/content-schema/world-authoring"))
import world_region_codec as codec

PLACEMENTS = ROOT / "content/world/placements"
OUTPUT = (
    ROOT / "crates/gameplay/dispatch/src/gameplay_transport"
    / "actor_movement/observer_eye/bindings.rs"
)


def compile_bindings():
    palette = json.loads((PLACEMENTS / "index.json").read_text())["palette"]
    region = PLACEMENTS / "region-z14-x128-y128.b3"
    floor, _, _, sectors = codec.decode_region(region.read_bytes())
    tiles = {
        (x, y): [palette[index]["source_item_id"] for index, depth, _ in items if depth == 0]
        for _, sector in sectors
        for x, y, _, _, _, items in sector
        if 32775 <= x <= 32783 and 32907 <= y <= 32918
    }

    def find_tile(appearance):
        (position,) = (pos for pos, items in tiles.items() if appearance in items)
        return position

    topaz = find_tile(25200)
    emerald = find_tile(13494)
    lever = find_tile(9110)
    controls = sorted(find_tile(item) for item in range(24904, 24912))
    if any(max(abs(x - topaz[0]), abs(y - topaz[1])) != 1 for x, y in controls):
        raise ValueError("Observer Eye ornaments must surround the topaz")
    # Crystal 201189f8 data/items/items.xml:47937-47951. The baked field
    # includes the reserved appearance used for submerged platforms.
    platforms = {
        pos for pos, items in tiles.items()
        if any(item in range(24888, 24903) or item == 24912 for item in items)
    }
    if not platforms or emerald in platforms or lever in platforms:
        raise ValueError("Observer Eye platform or pad binding has drifted")
    output = [
        "// Generated by tools/content-schema/quest-authoring/opticording_observer_eye.py.",
        "// Source: content/world/placements/region-z14-x128-y128.b3.",
        "",
        f"pub(super) const FLOOR: i16 = {floor};",
        f"pub(super) const TOPAZ: (i32, i32) = {topaz};",
        f"pub(super) const EMERALD: (i32, i32) = {emerald};",
    ]
    for name, positions in [
        ("CONTROLS", controls),
        ("WEST_FIELD", sorted(platforms | {emerald, lever})),
    ]:
        output.append(f"pub(super) const {name}: &[(i32, i32)] = &[")
        output.extend(f"    {position}," for position in positions)
        output.append("];")
    return "\n".join(output) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = compile_bindings()
    if args.check:
        if OUTPUT.read_text() != data:
            raise SystemExit("Observer Eye movement bindings need regeneration")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(data)


if __name__ == "__main__":
    main()
