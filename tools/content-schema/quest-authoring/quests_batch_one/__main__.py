"""Generate/check the reviewed first-batch quest documents from pinned Crystal."""

import argparse
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from quests_batch_one.source import Source
from quests_batch_one.source_dialogues import supplement


def documents(source, quests):
    result = {}
    for quest in quests:
        if quest == "dark_trails":
            from quests_batch_one import dark_trails

            generated = dark_trails.build(source)
            key = "content/dialogues/quests/dark-trails.json"
            generated[key] = supplement(source, quest, generated[key])
        elif quest == "spike_tasks":
            from quests_batch_one import spike_tasks

            generated = spike_tasks.build(source)
        elif quest == "what_a_foolish_quest":
            from quests_batch_one import foolish_dialogues

            generated = foolish_dialogues.build(source)
            key = "content/dialogues/quests/what-a-foolish.json"
            generated[key] = supplement(source, quest, generated[key])
        else:
            from quests_batch_one import greetings

            generated = greetings.build(source)
        result.update(generated)
    return result


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--crystal-root",
        type=Path,
        required=True,
        help="Git repository containing the prescribed Crystal commit; worktree is never read",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[4],
        help="Oteryn repository/output root",
    )
    parser.add_argument(
        "--quest",
        action="append",
        choices=("dark_trails", "spike_tasks", "what_a_foolish_quest", "greetings"),
    )
    parser.add_argument(
        "--check", action="store_true", help="Compare exact bytes; do not write"
    )
    args = parser.parse_args(argv)
    source = Source(args.crystal_root)
    selected = args.quest or [
        "dark_trails",
        "spike_tasks",
        "what_a_foolish_quest",
        "greetings",
    ]
    failed = []
    for relative, document in documents(source, selected).items():
        # The static greeting file's original ASCII representation is preserved.
        encoded = (
            json.dumps(
                document,
                ensure_ascii=relative.endswith("batch-one-greetings.json"),
                indent=2,
            )
            + "\n"
        ).encode("utf-8")
        target = args.output / relative
        if args.check:
            if not target.is_file() or target.read_bytes() != encoded:
                failed.append(relative)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(encoded)
        print(f"{relative} sha256={hashlib.sha256(encoded).hexdigest()}")
    if failed:
        parser.exit(1, "Generated bytes differ: " + ", ".join(failed) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
