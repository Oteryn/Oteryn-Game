#!/usr/bin/env python3
"""Generate Hireling economic facts from the exact pinned Crystal NPC source.

Usage: generate_catalogue.py path/to/data-global/npc/hireling.lua [--check]
No network fetch or hand-maintained prices: changed source bytes fail closed.
"""
from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

REVISION = "201189f871d23597b82caf88fd611454a2ddefb8"
SOURCE_SHA256 = "d507c31db74a3558d27bfec6bd08a45076742e6f5ea6da5f5d2baccfc08faf5f"
OUTPUT = Path(__file__).resolve().parents[3] / "crates/gameplay/domain/src/domain/hireling/catalogue/generated.rs"


def extract(source: str):
    """One pinned parser shared by the Rust catalogue and native Item closure."""
    if hashlib.sha256(source.encode()).hexdigest() != SOURCE_SHA256:
        raise ValueError("source is not Crystal 201189f data-global/npc/hireling.lua")
    categories: list[str] = []
    rows: list[tuple[int, int, int, int, int, int]] = []
    packages: list[tuple[str, int, list[tuple[int, int]], int]] = []
    category = -1
    disabled: list[tuple[str, int]] = []
    package = None
    mode = "trade"
    for number, line in enumerate(source.splitlines(), 1):
        if "local playerImbuementData" in line:
            mode = "between"
        if "local imbuementPackagesData" in line:
            mode = "packages"
        if "-- On buy npc shop message" in line:
            mode = "done"
        name = re.match(r'\t\t\["([^"]+)"\] = \{', line)
        if mode == "trade":
            if name:
                categories.append(name[1])
                category = len(categories) - 1
            if line.lstrip().startswith("--") and "clientId" in line:
                label = re.search(r'itemName = "([^"]+)"', line)
                if label is None or re.search(r"clientId\s*=\s*\d+", line):
                    raise ValueError("unrecognized disabled source row")
                disabled.append((label[1], number))
                continue
            fields = dict(re.findall(r"(clientId|buy|sell|subType)\s*=\s*(\d+)", line))
            if "clientId" in fields:
                rows.append((category, int(fields["clientId"]), int(fields.get("buy", 0)),
                             int(fields.get("sell", 0)), int(fields.get("subType", 0)), number))
        elif mode == "packages":
            if name:
                package = [name[1], 0, [], number]
                packages.append(package)
            price = re.search(r"moneyRequired = (\d+)", line)
            item = re.search(r"itemId = (\d+), count = (\d+)", line)
            if price and package is not None:
                package[1] = int(price[1])
            if item and package is not None:
                package[2].append((int(item[1]), int(item[2])))
    if disabled != [("putrefactive figurine", 1468), ("vemiath's infused basalt", 1630)]:
        raise ValueError("disabled donor placeholders changed")
    if len(categories) != 12 or len(rows) != 1675 or len(packages) != 23:
        raise ValueError("incomplete source extraction")
    if sum(row[0] == 11 for row in rows) != 1376:
        raise ValueError("buy-loot source rows were lost")
    if any(len(package[2]) != 3 or package[1] <= 0 for package in packages):
        raise ValueError("invalid package extraction")
    return categories, rows, packages, disabled


def generate(source: str) -> str:
    categories, rows, packages, disabled = extract(source)
    output = ["// Generated by tools/content-schema/hireling/generate_catalogue.py; do not edit.",
              f"// Crystal {REVISION}, data-global/npc/hireling.lua.",
              "use super::{DisabledRow, Package, TradeRow};", "",
              f'pub const SOURCE_SHA256: &str = "{SOURCE_SHA256}";',
              "pub const CATEGORIES: [&str; 12] = ["]
    output.extend(f'    "{name}",' for name in categories)
    output += ["];", "", "pub const DISABLED_ROWS: [DisabledRow; 2] = ["]
    for name, line in disabled:
        output.extend(["    DisabledRow {", f'        name: "{name}",',
                       f"        source_line: {line},", "    },"])
    output += ["];", "", "#[rustfmt::skip]", "pub static ROWS: &[TradeRow] = &["]
    output.extend("    TradeRow {{ category: {}, item_id: {}, buy: {}, sell: {}, sub_type: {}, source_line: {} }},".format(*row) for row in rows)
    output += ["];", "", "#[rustfmt::skip]", "pub static PACKAGES: &[Package] = &["]
    for name, gold, items, line in packages:
        entries = ", ".join(f"({item}, {count})" for item, count in items)
        output.append(f'    Package {{ name: "{name}", gold: {gold}, items: [{entries}], source_line: {line} }},')
    output += ["];", ""]
    return "\n".join(output)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = generate(args.source.read_text())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != rendered:
            raise SystemExit("Hireling catalogue differs from pinned donor generation")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(rendered)
    print("HIRELING_CATALOGUE_VERIFIED rows=1675 buy_loot=1376 disabled_source_rows=2 packages=23")


if __name__ == "__main__":
    main()
