#!/usr/bin/env python3
"""Capture effective ordered Soul War death registrations from exact pinned Lua."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re
from build_srx3_soul_war_witness import CALLBACKS, KEYS, PIN, ROOT, build as witness_build
from death_event_source import ordered_death_events, monster_registrations

OUTPUT = ROOT / 'tools/content-schema/native-gameplay/srx3-soul-war-death-events.json'
KEY_OUTPUT = ROOT / 'crates/gameplay/content/src/content/native_soul_war_death_keys.rs'
MECHANICS = 'data-global/scripts/quests/soul_war/soul_war_mechanics.lua'
MIRROR = 'data-global/scripts/creaturescripts/monster/mirror_image_transform.lua'

def build(source_root: Path, tree: dict) -> dict:
    if tree['sha'] != PIN or tree.get('truncated'):
        raise ValueError('exact complete Crystal source tree required')
    blobs = {row['path']: row['sha'] for row in tree['tree'] if row['type'] == 'blob'}
    def read(path):
        raw = (source_root/path).read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        blob = hashlib.sha1(f'blob {len(raw)}\0'.encode()+raw).hexdigest()
        if digest != CALLBACKS[path] or blob != blobs[path]:
            raise ValueError('unqualified pinned death source: '+path)
        return raw
    bodies = {path: read(path) for path in CALLBACKS
              if path.startswith('data-global/monster/') or path in (MECHANICS, MIRROR)}
    normalize = lambda value: re.sub('[^a-z0-9]', '', value.lower())
    parents = []
    names = set()
    for key in KEYS:
        matches = [path for path in bodies if path.startswith('data-global/monster/')
                   and normalize(Path(path).stem) == normalize(key)]
        if len(matches) != 1:
            raise ValueError('ambiguous or absent source parent: '+key)
        path = matches[0]
        registrations = monster_registrations(bodies[path].decode())
        names.update(row['name'] for row in registrations)
        parents.append((key,path))
    sources = {}
    for name in names:
        matches = [path for path in (MECHANICS,MIRROR)
                   if ('CreatureEvent("'+name+'")').encode() in bodies[path]]
        if len(matches) != 1:
            raise ValueError('ambiguous or absent registered source event: '+name)
        path = matches[0]
        sources[name] = (path,bodies[path])
    rows = []
    for key,path in parents:
        result = ordered_death_events(bodies[path], sources)
        rows.append({'creature_key':'oteryn:creature.'+key,
                     'creature_revision':'definition-r1',
                     'parent_path':path, 'parent_git_blob':blobs[path], **result})
    # This generator is independently guarded by the existing complete native
    # witness's canonical bodies, source links and root digest.
    witness = witness_build()
    return {'schema':'SRX3_SOUL_WAR_ORDERED_DEATH_EVENTS/v1',
            'source_repository':'zimbadev/crystalserver','source_revision':PIN,
            'source_definitions_sha256':witness['source_definitions_sha256'],
            'sources':[{'path':path,'git_blob':blobs[path], 'sha256':CALLBACKS[path]}
                       for path in sorted(bodies)],
            'records':rows}

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-root',type=Path,required=True)
    parser.add_argument('--tree',type=Path,required=True)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    result=build(args.source_root,json.loads(args.tree.read_bytes()))
    raw=(json.dumps(result,sort_keys=True,indent=2)+'\n').encode()
    keys = '// Generated by build_srx3_soul_war_death_events.py; do not edit.\n' + 'pub(super) const COVERED_KEYS: &[&str] = &[\n' + ''.join('    '+json.dumps(row['creature_key'])+',\n' for row in result['records']) + '];\n'
    if args.check:
        if OUTPUT.read_bytes()!=raw or KEY_OUTPUT.read_text()!=keys:
            raise SystemExit('stale Soul War ordered death capture/key guard')
    else:
        OUTPUT.write_bytes(raw)
        KEY_OUTPUT.write_text(keys)
    print(f"{len(result['records'])} source-qualified parents; "
          f"{sum(bool(row['on_death']) for row in result['records'])} nonempty death vectors")

if __name__=='__main__':main()
