#!/usr/bin/env python3
"""Generate bundle relocation facts from one hash-verified Canary source cut.

Inputs are reference data, never executed. No source graphics are retained.
Uses the existing appearances/XML loader used by the qualified spell world.
"""
import argparse
import hashlib
from pathlib import Path

from build_source_world import bool_xml, fields, policies

REVISION = "47dfd51f45280a59a1d3e50ba7edd573d7234446"
INPUTS = {
    "data/items/appearances.dat": "aa44a154f30c7ed59acc25f246286396e4043851ef0b54ef3cf3951e46d1ce50",
    "data/items/items.xml": "1cf2992cdd7cc5b97bcf930b8c89676ec1627170008e995fd2576110e26022f2",
}
ROOT = Path(__file__).resolve().parents[3]
OUTPUT = ROOT / "crates/gameplay/world/src/map/spell_tiles/immovable_catalogue.rs"


def generate(source_root):
    raw = {}
    for name, expected in INPUTS.items():
        raw[name] = (source_root / name).read_bytes()
        if hashlib.sha256(raw[name]).hexdigest() != expected:
            raise ValueError(f"source digest mismatch: {name} at {REVISION}")
    appearances = raw["data/items/appearances.dat"]
    ids = {fields(obj)[1][0] for obj in fields(appearances)[1]}
    if not ids or min(ids) < 1 or max(ids) > 65535:
        raise ValueError("source id bounds")
    encoded = ["?"] * (max(ids) + 1)
    for policy in policies(appearances, raw["data/items/items.xml"], ids):
        # ItemParse::parseWalk (item_parse.cpp:809-813) overrides appearance solidity.
        for attribute in policy["xml_attributes"]:
            if attribute.get("key", "").lower() == "blocking":
                policy["block_solid"] = bool_xml(attribute.get("value", ""))
        mask = (
            int(policy["block_solid"])
            | (int(policy["block_pathfind"]) << 1)
            | (int(policy["magic_field"]) << 2)
            | (int(policy["movable"]) << 3)
        )
        encoded[policy["server_item_id"]] = chr(ord("A") + mask)
    data = "".join(encoded)
    lines = [
        "// Generated by tools/content-schema/native-gameplay/build_bundle_immovable.py.",
        f"// Canary {REVISION}; OTS_HYPOTHESIS_ONLY.",
        "// ASCII A..P encode solid=1, pathfind=2, magic_field=4, movable=8; ? is unknown.",
        "// Index is the source appearance id. Placement overrides are applied by immovable.rs.",
        "pub(super) const FLAGS: &str = concat!(",
    ]
    lines.extend(f'    "{data[i:i + 96]}",' for i in range(0, len(data), 96))
    lines.append(");")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate(args.source_root)
    if args.check:
        if OUTPUT.read_text() != expected:
            raise SystemExit("bundle immovable catalogue drift")
    else:
        OUTPUT.write_text(expected)


if __name__ == "__main__":
    main()
