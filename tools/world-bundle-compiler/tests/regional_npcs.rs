// Additional contacts for the same NPCs from the other NPC content lanes.
const PACKAGE_CONTACTS: &[(&str, u16, u16, u8)] = &[
    ("oteryn:npc.brodrosch", 32659, 31958, 15),
    ("oteryn:npc.xodet", 32251, 32207, 11),
];

#[test]
fn six_region_npcs_are_loaded_at_qualified_source_cells() -> Result<(), Box<dyn std::error::Error>>
{
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let selected: Vec<_> = CONTACTS
        .iter()
        .map(|&(_, x, y, _)| (x / 256, y / 256))
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect();
    let project = source::project_regions(&root, &selected)?;
    let (registry, palette) = source::registry(&root, &project)?;
    let input = Input {
        regions: &project.regions,
        palette: &palette,
        identity: Identity::default(),
        world: source::world_extent(&root)?,
        build_class: BuildClass::NonProduction,
        draft_areas: Vec::new(),
        families: &project.families,
    };
    let compiled = compile(&input, &registry)?;
    assert!(
        compiled.npcs.routes_held.iter().all(|route| {
            route.reason != oteryn_world_bundle_compiler::compile::HoldReason::NpcPlacement
        }),
        "travel arrivals must remain clear: {:?}",
        compiled
            .npcs
            .routes_held
            .iter()
            .filter(|route| {
                route.reason == oteryn_world_bundle_compiler::compile::HoldReason::NpcPlacement
            })
            .collect::<Vec<_>>(),
    );
    let realized = bundle::visit(&compiled.bytes, |_, _| Ok(()))?.npcs;
    let contacts: BTreeSet<_> = CONTACTS.iter().map(|row| row.0).collect();
    let actual: BTreeSet<_> = realized
        .npcs
        .iter()
        .filter(|npc| contacts.contains(npc.key.as_str()))
        .flat_map(|npc| {
            npc.placements
                .iter()
                .map(|p| (npc.key.as_str(), p.x, p.y, p.floor.unsigned_abs()))
        })
        .collect();
    let expected: BTreeSet<_> = CONTACTS.iter().chain(PACKAGE_CONTACTS).copied().collect();
    assert_eq!(
        actual,
        expected,
        "missing contacts: {:?}; unexpected contacts: {:?}",
        expected.difference(&actual).collect::<Vec<_>>(),
        actual.difference(&expected).collect::<Vec<_>>(),
    );
    Ok(())
}
