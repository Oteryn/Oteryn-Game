const LOCK: &str = r#"# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "oteryn-world-bundle"
version = "0.1.0"
dependencies = [
 "sha2 0.11.1",
]

[[package]]
name = "oteryn-world-bundle-compiler"
version = "0.1.0"
dependencies = [
 "oteryn-world-bundle",
 "sha2 0.11.1 (registry+https://github.com/rust-lang/crates.io-index)",
]

[[package]]
name = "sha2"
version = "0.10.9"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "aaaa"

[[package]]
name = "sha2"
version = "0.11.1"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "bbbb"
dependencies = [
 "cfg-if",
]

[[package]]
name = "cfg-if"
version = "1.0.4"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "cccc"

[[package]]
name = "other-app"
version = "0.1.0"
dependencies = [
 "sha2 0.10.9",
]
"#;

fn closure(lock: &str) -> Result<(String, BTreeSet<String>), Error> {
    lock_closure(lock)
}

#[test]
fn the_lock_closure_holds_the_world_crates_and_what_they_reach() -> Result<(), Error> {
    let (text, names) = closure(LOCK)?;
    let expected: BTreeSet<String> = [
        "cfg-if",
        "oteryn-world-bundle",
        "oteryn-world-bundle-compiler",
        "sha2",
    ]
    .map(str::to_owned)
    .into();
    assert_eq!(names, expected);
    assert!(text.starts_with("lock format 4\n"), "{text}");
    assert!(text.contains("sha2 0.11.1 registry+"), "{text}");
    assert!(!text.contains("0.10.9"), "{text}");
    assert!(!text.contains("other-app"), "{text}");

    // An unrelated package and an unrelated edge do not move it.
    let unrelated = LOCK.replace(
        " \"sha2 0.10.9\",\n]",
        " \"sha2 0.10.9\",\n \"cfg-if\",\n]\n\n[[package]]\nname = \"extra\"\nversion = \"1.0.0\"\n\
         source = \"registry+https://github.com/rust-lang/crates.io-index\"\nchecksum = \"dddd\"",
    );
    assert_ne!(unrelated, LOCK);
    assert_eq!(closure(&unrelated)?.0, text);
    // A dependency named without its version once it is unique moves nothing either.
    let respelled = LOCK.replace(
        " \"sha2 0.11.1\",\n]",
        " \"sha2 0.11.1 (registry+https://github.com/rust-lang/crates.io-index)\",\n]",
    );
    assert_ne!(respelled, LOCK);
    assert_eq!(closure(&respelled)?.0, text);

    // A checksum, a version or an edge of a package in the closure does.
    assert_ne!(closure(&LOCK.replace("cccc", "eeee"))?.0, text);
    assert_ne!(closure(&LOCK.replace("1.0.4", "1.0.5"))?.0, text);
    let dropped_edge = LOCK.replace("dependencies = [\n \"cfg-if\",\n]\n", "");
    assert_ne!(closure(&dropped_edge)?.0, text);
    Ok(())
}

#[test]
fn the_lock_reader_fails_closed() {
    // A path package the World crates reach must be a World crate.
    let path_dependency = LOCK.replace(
        " \"oteryn-world-bundle\",\n",
        " \"oteryn-world-bundle\",\n \"other-app\",\n",
    );
    assert!(
        matches!(closure(&path_dependency), Err(Error::Format(what)) if what.contains("other-app"))
    );
    for bad in [
        LOCK.replace("version = 4", "version = 2"),
        LOCK.replace("version = 4\n", ""),
        LOCK.replace(
            "checksum = \"cccc\"",
            "checksum = \"cccc\"\nreplace = \"x\"",
        ),
        LOCK.replace(
            "[[package]]\nname = \"other-app\"",
            "[metadata]\nname = \"other-app\"",
        ),
        // An ambiguous and a dangling dependency.
        LOCK.replace(" \"sha2 0.11.1\",\n]", " \"sha2\",\n]"),
        LOCK.replace(" \"cfg-if\",\n]", " \"cfg-if 9.9.9\",\n]"),
        LOCK.replace("name = \"oteryn-world-bundle\"\n", "name = \"renamed\"\n"),
        LOCK.replace(" \"cfg-if\",\n]", " \"cfg-if\"\n]"),
        LOCK.replace(
            "checksum = \"cccc\"\n",
            "checksum = \"cccc\"\ndependencies = [\n \"sha2 0.10.9\",\n",
        ),
    ] {
        assert!(closure(&bad).is_err(), "{bad}");
    }
    // An unused patch is skipped.
    let unused = format!("{LOCK}\n[[patch.unused]]\nname = \"x\"\nversion = \"1.0.0\"\n");
    assert!(closure(&unused).is_ok());
}

const MANIFEST: &str = r#"[workspace]
members = [
    "crates/world-bundle",
    "tools/world-bundle-compiler", # the compiler
    "apps/a[1]",
]
exclude = ["vendor/x"]
resolver = "3"

[workspace.package]
version = "0.1.0"

[workspace.dependencies]
# A comment.
rcgen = { version = "=0.14.10", default-features = false, features = ["crypto"] }
sha2 = { version = "=0.11.1", default-features = false }
sqlx = {
    version = "=0.9.0",
    features = [
        "postgres",
    ],
}
renamed = { package = "other", version = "1" }
"quoted" = "1"

[patch.crates-io]
tokio = { path = "vendor/tokio" }

[workspace.lints.rust]
unsafe_code = "forbid"
"#;

fn names(list: &[&str]) -> BTreeSet<String> {
    list.iter().map(|name| (*name).to_owned()).collect()
}

#[test]
fn the_workspace_manifest_keeps_what_reaches_the_world_crates() -> Result<(), Error> {
    let world = names(&["sha2", "oteryn-world-bundle"]);
    let text = workspace_manifest(MANIFEST, &world)?;
    for kept in [
        "resolver = \"3\"",
        "[workspace.package]",
        "sha2 = { version = \"=0.11.1\"",
        "renamed = {",
        "\"quoted\" = \"1\"",
        "tokio = { path = \"vendor/tokio\" }",
        "unsafe_code = \"forbid\"",
    ] {
        assert!(text.contains(kept), "{kept}: {text}");
    }
    for dropped in [
        "members",
        "exclude",
        "rcgen",
        "sqlx",
        "postgres",
        "A comment",
    ] {
        assert!(!text.contains(dropped), "{dropped}: {text}");
    }

    // A member, an exclude entry, an unrelated workspace dependency or a comment moves nothing.
    for unrelated in [
        MANIFEST.replace(
            "    \"apps/a[1]\",\n",
            "    \"apps/a[1]\",\n    \"apps/b\",\n",
        ),
        MANIFEST.replace("[\"vendor/x\"]", "[\"vendor/x\", \"vendor/y\"]"),
        MANIFEST.replace("=0.14.10", "=0.14.11"),
        MANIFEST.replace("\"=0.9.0\"", "\"=0.9.1\""),
        MANIFEST.replace("# A comment.", "# Another comment.\n\nnew-crate = \"1\""),
    ] {
        assert_ne!(unrelated, MANIFEST);
        assert_eq!(workspace_manifest(&unrelated, &world)?, text, "{unrelated}");
    }

    // A World dependency, a renamed entry, a profile, a patch or a lint moves it.
    for related in [
        MANIFEST.replace("=0.11.1", "=0.11.2"),
        MANIFEST.replace("version = \"1\" }", "version = \"2\" }"),
        format!("{MANIFEST}\n[profile.release]\nopt-level = 2\n"),
        MANIFEST.replace("vendor/tokio\"", "vendor/tokio-2\""),
        MANIFEST.replace("\"forbid\"", "\"deny\""),
        MANIFEST.replace("resolver = \"3\"", "resolver = \"2\""),
    ] {
        assert_ne!(workspace_manifest(&related, &world)?, text, "{related}");
    }
    // An rcgen entry counts once rcgen is in the closure.
    assert!(workspace_manifest(MANIFEST, &names(&["rcgen"]))?.contains("rcgen"));
    Ok(())
}

#[test]
fn the_workspace_manifest_reader_fails_closed() {
    for bad in [
        "[workspace]\nmembers = [\n    \"a\",\n",
        "[workspace]\nmembers = [\"a]\n",
        "[workspace]\nnot a key\n",
        "[workspace]\nmembers = [\"a\"]]\n",
    ] {
        assert!(workspace_manifest(bad, &BTreeSet::new()).is_err(), "{bad}");
    }
}

#[test]
fn the_world_crates_are_listed_inputs_named_by_their_manifests() -> Result<(), Error> {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    for (name, directory) in WORLD_PACKAGES {
        assert!(INPUT_PATHS.contains(directory), "{directory}");
        let manifest = read(&root.join(directory).join("Cargo.toml"))?;
        assert_eq!(
            package_name(&String::from_utf8_lossy(&manifest)).as_deref(),
            Some(*name)
        );
    }
    // The repository lock and manifest read cleanly, and the closure is the small World one.
    let lock = String::from_utf8_lossy(&read(&root.join("Cargo.lock"))?).into_owned();
    let (_, closure) = lock_closure(&lock)?;
    for name in ["oteryn-world-bundle", "serde", "sha2", "zstd"] {
        assert!(closure.contains(name), "{name}");
    }
    for name in ["tokio", "wgpu", "rustls", "sqlx", "oteryn-game-server"] {
        assert!(!closure.contains(name), "{name}");
    }
    let manifest = String::from_utf8_lossy(&read(&root.join("Cargo.toml"))?).into_owned();
    let text = workspace_manifest(&manifest, &closure)?;
    assert!(
        !text.contains("apps/client") && !text.contains("rcgen"),
        "{text}"
    );
    assert!(
        text.contains("[workspace.lints.clippy]") && text.contains("sha2 = "),
        "{text}"
    );
    Ok(())
}
