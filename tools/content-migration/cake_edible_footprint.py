 sql+="REVOKE ALL ON FUNCTION game_cake_edible_goal() FROM PUBLIC,oteryn_game_control;\nGRANT EXECUTE ON FUNCTION game_cake_edible_goal() TO oteryn_game_runtime;\n"
 outputs={'tools/content-schema/native-gameplay/seasonal-cake-footprint.sql':sql,OUTPUT:json.dumps(data,sort_keys=True,indent=2)+'\n',GOAL_CELLS:json.dumps([row[:3] for row in data['cells']],separators=(',',':'))+'\n','crates/gameplay/durability/src/durability/seasonal_cake/footprint.rs':rust}
