import subprocess

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'tools/content-schema/world-authoring'))
import world_region_codec as codec
LOWER='content/world/placements/region-z07-x130-y125.b3'
SOURCE_SHA='2798be76221d6dc00695258d46d1eb375a64e804a7a84265014e2af0c679b05d'
OUTPUT='tools/content-schema/native-gameplay/seasonal-cake-footprint.json'
GOAL_CELLS='crates/gameplay/dispatch/src/gameplay_transport/postgres_tests/seasonal_cake_goal_cells.json'

def capture(root=ROOT):
 raw=(root/LOWER).read_bytes()
 if hashlib.sha256(raw).hexdigest()!=SOURCE_SHA:raise ValueError('CAKE_QUALIFIED_SOURCE_REGION_DRIFT')
 palette=json.loads((root/'content/world/placements/index.json').read_bytes())['palette']
 ids={i:row['source_item_id'] for i,row in enumerate(palette)}
 cells=[];corners=[];bare=[]
 for _,tiles in codec.decode_region(raw)[3]:
  for x,y,flags,house,zones,items in tiles:
   if not(33287<=x<=33330 and 32065<=y<=32103):continue
   food=[(ordinal,ids[pid]) for ordinal,(pid,depth,attrs) in enumerate(items) if depth==0 and ids[pid] in (12085,12086)]
   corner=any(depth==0 and ids[pid] in (12087,12088,12089) for pid,depth,attrs in items)
   if food:
    if len(food)!=1 or corner:raise ValueError('CAKE_ONE_ACTUAL_EDIBLE_PER_NONCORNER_CELL')
    ordinal,item=food[0];cells.append([x,y,item,ordinal])
   elif corner:corners.append([x,y])
   elif len(items)==1 and ids[items[0][0]] in range(12090,12096):bare.append([x,y])
 cells.sort(key=lambda r:(r[1],r[0]));corners.sort();bare.sort()
 if len(cells)!=1066 or len(corners)!=49 or bare!=[[33318,32069]]:raise ValueError('CAKE_PINNED_EDIBLE_CORNER_CENSUS')
 upper=[]
 for z in (4,5,6):
  path=f'content/world/placements/region-z{z:02}-x130-y125.b3';data=(root/path).read_bytes();decor=set();borders=set()
  for _,tiles in codec.decode_region(data)[3]:
   for x,y,flags,house,zones,items in tiles:
    if not(33287<=x<=33330 and 32065<=y<=32103):continue
    for pid,depth,attrs in items:
     if depth!=0:continue
     if ids[pid] in (12147,12148):decor.add((x,y))
     if ids[pid] in (12152,12153,12154,12155):borders.add((x,y))
  if len(decor)!=1116 or not {(x,y) for x,y,_,_ in cells}.issubset(decor):raise ValueError('CAKE_UPPER_DECORATION_NOT_EDIBLE_GOAL')
  upper.append({'floor':z,'decoration_cells':len(decor),'border_cells':len(borders),'sha256':hashlib.sha256(data).hexdigest()})
 return {'schema':'OTERYN_SEASONAL_CAKE_FOOTPRINT/v1','source_revision':'201189f871d23597b82caf88fd611454a2ddefb8','b3_path':LOWER,'b3_sha256':SOURCE_SHA,'accepted_ids':[12085,12086],'layer_goals':[len(cells)]*4,'cells':cells,'excluded_corners':corners,'preserved_bare_bases':bare,'upper_decoration_audit':upper}

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args();data=capture()
 rust="// @generated by tools/content-migration/cake_edible_footprint.py; map geometry is unchanged.\n"
 rust+=f"pub const SOURCE_REGION_SHA256: &str = \"{SOURCE_SHA}\";\n"
 rust+="pub const LAYER_GOALS: [u16;4] = ["+','.join(map(str,data['layer_goals']))+"];\n"
 rust+="pub const EDIBLE_CELLS: &[(u16,u16,u16)] = &[\n"+''.join(f"({x},{y},{item}),\n" for x,y,item,_ in data['cells'])+"];\n"
 rust+="pub fn layer_goal(layer:u8)->Option<u16>{LAYER_GOALS.get(usize::from(layer).checked_sub(1)?).copied()}\n"
 rust+="pub fn is_edible_cell(x:u16,y:u16,item:u16)->bool{EDIBLE_CELLS.binary_search_by_key(&(y,x),|(x,y,_)|(*y,*x)).ok().is_some_and(|i|EDIBLE_CELLS[i].2==item)}\n"
 rust=subprocess.run(['rustfmt','--edition','2024'],input=rust,text=True,stdout=subprocess.PIPE,check=True).stdout
 sql="-- @generated by tools/content-migration/cake_edible_footprint.py; actual floor7 edible cells.\n"
 sql+="-- Source region SHA256 "+SOURCE_SHA+"\n"
 sql+="CREATE TABLE game_cake_edible_cells(x INTEGER NOT NULL,y INTEGER NOT NULL,appearance INTEGER NOT NULL,stack SMALLINT NOT NULL,PRIMARY KEY(x,y));\nINSERT INTO game_cake_edible_cells VALUES\n"
 sql+=',\n'.join('('+','.join(map(str,row))+')' for row in data['cells'])+';\n'
 sql+="REVOKE ALL ON game_cake_edible_cells FROM PUBLIC,oteryn_game_runtime,oteryn_game_control;\n"
