#!/usr/bin/env python3
"""Project known immovable ladder appearances from the authoritative world catalogue."""
import argparse
import json
from pathlib import Path


def render(root: Path) -> str:
    ids = set()
    for source in sorted((root / "content/world/objects").glob("*.json")):
        for record in json.loads(source.read_text()).get("records", []):
            if record.get("kind") != {"state": "KNOWN", "value": "ladder"}:
                continue
            if record.get("movable") != {"state": "KNOWN", "value": False}:
                raise ValueError("ladder must have known immovable ownership")
            projection = record["client_projection"]
            if projection["state"] != "KNOWN":
                raise ValueError("ladder appearance must be known")
            ids.add(projection["value"]["appearance_id"])
    if not ids or any(not 0 < value <= 65535 for value in ids):
        raise ValueError("invalid ladder catalogue")
    return ("//! Generated by tools/content-migration/build_ladder_catalogue.py.\n"
            "//! Known immovable ladder appearances from content/world/objects.\n"
            "#[rustfmt::skip]\n"
            "pub(super) const LADDERS: &[u16] = &[\n"
            + "".join(f"    {value},\n" for value in sorted(ids)) + "];\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    repository = Path(__file__).resolve().parents[2]
    output = repository / "crates/gameplay/world/src/map/ladder_catalogue.rs"
    expected = render(repository)
    if args.check:
        if output.read_text() != expected:
            raise SystemExit("ladder catalogue is stale")
    else:
        output.write_text(expected)
