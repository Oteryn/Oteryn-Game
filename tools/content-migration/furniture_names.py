"""SRX-1: display names for the existing closed Crystal furniture catalogue."""
import argparse
import hashlib
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
SHA='8a4a526c6e45b5a282679334eb1e1e25a5b72af13aa92c8a0d409755ebdbc509'
DEST='crates/gameplay/dispatch/src/gameplay_transport/furniture_catalog_names.rs'


def output(xml):
    raw=xml.read_bytes()
    if hashlib.sha256(raw).hexdigest()!=SHA:
        raise ValueError('FURNITURE_XML_DIGEST')
    catalogue=(ROOT/'crates/gameplay/dispatch/src/gameplay_transport/furniture_catalog.rs').read_text()
    wrap,kits=catalogue.split('pub const CONSTRUCTION_KITS',1)
    wanted=set()
    for low,high,target in re.findall(r'\((\d+), (\d+), (\d+)\)',wrap):
        wanted.update(range(int(low),int(high)+1));wanted.add(int(target))
    for source,target in re.findall(r'\((\d+), (\d+)\)',kits):
        wanted.update((int(source),int(target)))
    names={}
    for node in ET.fromstring(raw):
        low=int(node.get('id',node.get('fromid','0')));high=int(node.get('id',node.get('toid','0')))
        for item in wanted.intersection(range(low,high+1)):
            names[item]=node.attrib['name']
    if names.keys()!=wanted-{35027}: # Existing wrap table references this absent donor target.
        raise ValueError('FURNITURE_NAME_MISSING')
    lines=['//! Generated by tools/content-migration/furniture_names.py. Do not edit.',
           '//! Crystal 201189f871d23597b82caf88fd611454a2ddefb8 data/items/items.xml.',
           '#[rustfmt::skip]','pub(super) const NAMES: &[(u32, &str)] = &[']
    lines += [f'    ({item}, {json.dumps(name,ensure_ascii=False)}),' for item,name in sorted(names.items())]
    return '\n'.join([*lines,'];',''])


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--xml',required=True,type=Path)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args();expected=output(args.xml);dest=ROOT/DEST
    if args.check:
        if dest.read_text()!=expected:raise SystemExit('FURNITURE_NAMES_DRIFT')
    else:dest.write_text(expected)
