"""Generate the closed11-source seasonal actor appearance table from pinned Lua captures."""
import argparse,json,hashlib,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
INPUT='tools/content-schema/native-gameplay/seasonal-actor-looks.json'
OUTPUT='crates/gameplay/dispatch/src/gameplay_transport/seasonal_appearance/source.rs'
def generate(data):
 if data['schema']!='OTERYN_SEASONAL_ACTOR_LOOKS/v1':raise ValueError('SEASONAL_LOOK_SCHEMA')
 rows=data['records'];keys=[r['key']for r in rows]
 expected_npcs={'oteryn:npc.'+n for n in ['santa_claus','messenger_of_santa','balduin_the_baker','benny_the_baker','biff_the_baker','billy_the_baker','brian_the_baker','brutus_the_baker']}
 expected_creatures={'oteryn:creature.'+n for n in ['the_halloween_hare','the_mutated_pumpkin','cake_golem']}
 if {r['key']for r in rows if r['family']=='Npc'}!=expected_npcs or {r['key']for r in rows if r['family']=='Creature'}!=expected_creatures:raise ValueError('SEASONAL_CLOSED_SOURCE_ROSTER')
 for r in rows:
  source=r['source'];body=source['body']
  if source['revision']!='201189f871d23597b82caf88fd611454a2ddefb8' or hashlib.sha256(body.encode()).hexdigest()!=source['sha256']:raise ValueError('SEASONAL_SOURCE_BODY_SHA')
  m=re.search(r'(?:npcConfig|monster)\.outfit\s*=\s*\{([^{}]*)\}',body)
  if not m or body[:m.start()].count('\n')+1!=source['line']:raise ValueError('SEASONAL_OUTFIT_SOURCE_LINE')
  vals={k:int(v)for k,v in re.findall(r'([A-Za-z]+)\s*=\s*(\d+)\s*,?',m[1])}
  if re.sub(r'[A-Za-z]+\s*=\s*\d+\s*,?','',m[1]).strip():raise ValueError('SEASONAL_LITERAL_OUTFIT_ONLY')
  look={'kind':'Item','source_item_id':vals['lookTypeEx']} if 'lookTypeEx'in vals else{'kind':'Outfit','look_type':vals['lookType'],'colours':[vals.get(k,0)for k in ['lookHead','lookBody','lookLegs','lookFeet']],'addons':vals.get('lookAddons',0)}
  if look!=r['look']:raise ValueError('SEASONAL_LOOK_BODY_MISMATCH')
 if len(rows)!=11 or keys!=sorted(set(keys)) or sum(r['family']=='Npc'for r in rows)!=8:raise ValueError('SEASONAL_LOOK_ROSTER')
 text='// @generated by tools/content-migration/seasonal_actor_looks.py; finite source presentation only.\nuse super::SourceLook;\n'
 for family in ['Npc','Creature']:
  subset=[r for r in rows if r['family']==family];text+=f'pub(super) const {family.upper()}: &[(&str,SourceLook)] = &[\n'
  for r in subset:
   source=r['source'];look=r['look'];text+=f'// Crystal {source["revision"]} {source["path"]}:{source["line"]}; SHA256 {source["sha256"]}\n'
   if look['kind']=='Outfit':value=f'SourceLook::Outfit {{look_type:{look["look_type"]},colours:{look["colours"]},addons:{look["addons"]}}}'
   else:value=f'SourceLook::Item({look["source_item_id"]})'
   text+=f'("{r["key"]}",{value}),\n'
  text+='];\n'
 return text
if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args();data=json.loads((ROOT/INPUT).read_text());text=generate(data)
 import subprocess
 text=subprocess.run(['rustfmt','--edition','2024'],input=text,text=True,stdout=subprocess.PIPE,check=True).stdout
 path=ROOT/OUTPUT
 if a.check:
  if path.read_text()!=text:raise ValueError('SEASONAL_LOOK_GENERATED_DRIFT')
 else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text)
 print('SRV7_SEASONAL_SOURCE_LOOKS creatures=3 npcs=8')
