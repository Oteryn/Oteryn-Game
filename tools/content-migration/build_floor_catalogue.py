#!/usr/bin/env python3
"""Project native floor masks from the WorldObject and Terrain catalogues."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/content-schema/world-object-authoring"))

from activity_static import official_appearances
from crystal_traversal_facts import ITEM_FLOOR_CHANGES, WALKABLE_ITEM_FIXTURES

BITS = {
    "down": 1,
    "north": 2,
    "south": 4,
    "east": 8,
    "west": 16,
    "southalt": 32,
    "eastalt": 64,
}


def render(root: Path) -> str:
    lines = [
        "//! Generated by tools/content-migration/build_floor_catalogue.py from the",
        "//! WorldObject and Terrain catalogues (ADR-0021). Known facts only.",
        "//! Directions: down 1, north 2, south 4, east 8, west 16, southalt 32, eastalt 64.",
        "",
    ]
    for directory, stem, constant in [
        ("objects", "objects", "OBJECT"),
        ("terrain", "terrain", "TERRAIN"),
    ]:
        masks = {}
        for shard in (root / "content/world" / directory).glob(f"{stem}-*.json"):
            for record in json.loads(shard.read_bytes())["records"]:
                identifier = int(record["identity"]["key"].rsplit(".i", 1)[1])
                fact = record["floor_change"]
                if fact["state"] != "KNOWN":
                    continue
                if identifier in masks:
                    raise ValueError(f"{directory}: duplicate floor change {identifier}")
                masks[identifier] = BITS[fact["value"]]
        lines.append(f"pub(super) const {constant}: &[(u16, u8)] = &[")
        lines.extend(f"    ({identifier}, {mask})," for identifier, mask in sorted(masks.items()))
        lines.extend(["];", ""])
    appearances, members = official_appearances(root)
    fixture_ids = set(ITEM_FLOOR_CHANGES) | set(WALKABLE_ITEM_FIXTURES)
    for identifier in fixture_ids:
        flags = appearances[identifier]["flags"]
        if identifier not in members or not flags.get("flags.unmove") or flags.get("flags.unpass"):
            raise ValueError(f"Item {identifier} is not a fixed walkable fixture")
    item_facts = ", ".join(
        f"({identifier}, {BITS[direction]})"
        for identifier, direction in sorted(ITEM_FLOOR_CHANGES.items())
    )
    fixtures = ", ".join(str(identifier) for identifier in WALKABLE_ITEM_FIXTURES)
    lines.extend([
        f"pub(super) const ITEM: &[(u16, u8)] = &[{item_facts}];",
        "",
        "/// Source-qualified collision fallback for fixed Items on these traversal routes.",
        f"pub(super) const WALKABLE_TRAVERSAL_FIXTURES: &[u16] = &[{fixtures}];",
    ])
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "crates/gameplay/world/src/map/floor_catalogue.rs"
    expected = render(ROOT)
    if args.check:
        if output.read_text() != expected:
            raise SystemExit("floor catalogue is stale")
    elif not output.is_file() or output.read_text() != expected:
        output.write_text(expected)
