"""Primal's closed native provider cannot admit inventory or conflicting source facts."""
import copy
import hashlib
import json
from pathlib import Path
import tempfile
import unittest

import primal_item_profiles as primal


class PrimalItemProfiles(unittest.TestCase):
    def generated(self, records=()):
        return {'profiles': primal.canonical({'records': list(records)}),
                'manifest': primal.canonical({'item_profiles': {}})}

    def admit(self, generated):
        primal.admit(primal.ROOT, generated, 'profiles', 'manifest',
                     lambda row: row['production_definition']['production_key'], primal.canonical)

    def test_capture_preserves_all_five_ground_only_source_identities_and_decay_chain(self):
        document = primal.load_capture()
        self.assertEqual(document['item_ids'], list(primal.IDS))
        records = {int(row['production_binding']['external_id']): row for row in document['records']}
        for item, row in records.items():
            self.assertEqual(row['admission'], {'materializable': True, 'stack_class': 'NonStackable', 'legal_destinations': ['Ground']})
            self.assertEqual(row['production_binding']['source_revision'], primal.REVISION)
            self.assertEqual(row['production_definition']['production_key'], f'oteryn:item.tibia.i{item}')
        pod = records[39176]
        self.assertFalse(pod['attributes']['blocks_movement'])
        self.assertFalse(pod['attributes']['blocks_projectile'])
        physical = pod['semantics']['physical']['value']
        self.assertEqual(physical['movable'], primal.source.K(False))
        self.assertEqual(physical['pickupable'], primal.source.K(False))
        self.assertTrue(document['source_items'][0]['physical']['block_pathfind'])
        for item, capacity, duration, target in ((39530, 30, 10000, 39529), (39529, 30, 300000, 39528), (39528, 15, 300000, 39527), (39527, None, 60000, None)):
            row = records[item]
            container = primal.source.K({'capacity': primal.source.K(capacity)}) if capacity else primal.source.NA
            self.assertEqual(row['semantics']['container'], container)
            temporal = row['semantics']['temporal']['value']
            self.assertEqual(temporal['duration'], primal.source.K(duration))
            self.assertEqual(temporal['stop_duration'], primal.source.K(False))
            self.assertEqual(temporal['decay_target'], primal.source.K({'key': f'oteryn:item.tibia.i{target}', 'revision': 'definition-r1'}) if target else primal.source.NA)

    def test_provider_admits_exactly_five_and_repins_manifest_idempotently(self):
        generated = self.generated()
        self.admit(generated)
        first = copy.deepcopy(generated)
        self.assertEqual(len(json.loads(generated['profiles'])['records']), 5)
        self.assertEqual(json.loads(generated['manifest'])['item_profiles']['sha256'], hashlib.sha256(generated['profiles']).hexdigest())
        self.admit(generated)
        self.assertEqual(generated, first)

    def test_existing_identity_custody_and_physical_conflicts_refuse(self):
        source = primal.load_capture()['records'][0]
        for change, error in (
            (lambda row: row['production_binding'].update(source_revision='foreign'), 'IDENTITY_CONFLICT'),
            (lambda row: row['admission'].update(legal_destinations=['CharacterInventory', 'Ground']), 'CUSTODY_CONFLICT'),
            (lambda row: row['semantics']['physical']['value'].update(pickupable=primal.source.K(True)), 'SEMANTIC_CONFLICT'),
        ):
            row = copy.deepcopy(source)
            change(row)
            generated = self.generated([row])
            before = copy.deepcopy(generated)
            with self.assertRaisesRegex(ValueError, error):
                self.admit(generated)
            self.assertEqual(generated, before)

    def test_generated_cohort_receipt_preserves_every_other_row_and_exact_assertion(self):
        text = (primal.ROOT / primal.COHORT_LEDGER).read_text()
        prefix = '    // W10-PRIMAL: generated by primal_item_profiles.py --refresh-cohort.\n'
        evidence = ('    // Crystal ff7ede59 data/items/items.xml:71977,73314-73335; '
                    'Items 39176, 39527..=39530, speed_bonus=0.\n')
        owned = prefix + evidence + '    ("W10-PRIMAL", 5),\n'
        baseline = text.replace(owned, '')
        generated = primal.cohort_receipt(baseline, primal.load_capture())
        self.assertEqual(primal.cohort_receipt(generated, primal.load_capture()), generated)
        stale = generated.replace('("W10-PRIMAL", 5)', '("W10-PRIMAL", 1)')
        self.assertEqual(primal.cohort_receipt(stale, primal.load_capture()), generated)
        self.assertEqual(generated.count(owned), 1)
        self.assertEqual(generated.replace(owned, ''), baseline)
        self.assertIn('const ORIGINAL_PROFILES: usize = 432;', generated)
        self.assertLess(generated.index('("W07-SOULPIT",'), generated.index('("W10-PRIMAL",'))
        self.assertLess(generated.index('("W10-PRIMAL",'), generated.index('("W15C-GRIZZLY-DEBRIS",'))

    def test_cohort_receipt_rejects_foreign_keys_and_unowned_existing_rows(self):
        text = (primal.ROOT / primal.COHORT_LEDGER).read_text()
        changed = copy.deepcopy(primal.load_capture())
        changed['records'][0]['production_definition']['production_key'] = 'oteryn:item.tibia.i1'
        with self.assertRaisesRegex(ValueError, 'COHORT_IDENTITY_SET'):
            primal.cohort_receipt(text, changed)
        generated = primal.cohort_receipt(text, primal.load_capture())
        forged = generated.replace(
            '// W10-PRIMAL: generated by primal_item_profiles.py --refresh-cohort.',
            '// Unqualified caller supplied this cohort.')
        with self.assertRaisesRegex(ValueError, 'COHORT_RECEIPT_OWNERSHIP'):
            primal.cohort_receipt(forged, primal.load_capture())
        duplicated = generated.replace('    ("W10-PRIMAL", 5),',
                                       '    ("W10-PRIMAL", 5),\n    ("W10-PRIMAL", 500),')
        with self.assertRaisesRegex(ValueError, 'COHORT_LEDGER_IDENTITIES'):
            primal.cohort_receipt(duplicated, primal.load_capture())

    def test_source_hash_and_capture_mutations_refuse(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            path = root / 'data/items/items.xml'
            path.parent.mkdir(parents=True)
            path.write_bytes(b'<items/>')
            with self.assertRaisesRegex(ValueError, 'SOURCE_HASH'):
                primal.capture(root)
            capture = root / primal.PATH
            capture.parent.mkdir(parents=True)
            document = primal.load_capture()
            document['records'][0]['admission']['legal_destinations'].append('CharacterInventory')
            capture.write_bytes(primal.canonical(document))
            with self.assertRaisesRegex(ValueError, 'CAPTURE_DRIFT'):
                primal.load_capture(root)


if __name__ == '__main__':
    unittest.main()
