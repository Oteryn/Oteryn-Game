pub fn target(seal: u16) -> Option<SealTarget> {
    SEALS
        .get(usize::from(seal))
        .map(|&(position, ordinal)| SealTarget { position, ordinal })
}

/// Facts must come from the current retained map owner. This pure lookup does
/// not establish ownership, current appearance, range or permission to mutate.
pub fn paint_target(
    target: SealTarget,
    appearance: u16,
    snapshot: Snapshot,
) -> Result<Snapshot, QuestRefusal> {
    if appearance != 7178 {
        return Err(QuestRefusal::NotSupported);
    }
    let index = SEALS
        .iter()
        .position(|&(position, ordinal)| target.position == position && target.ordinal == ordinal)
        .ok_or(QuestRefusal::NotSupported)?;
    let index = u16::try_from(index).map_err(|_| QuestRefusal::NotSupported)?;
    super::paint(index, snapshot)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn source_seal_identity_requires_exact_floor_ordinal_and_appearance() -> Result<(), QuestRefusal>
    {
        let before = Snapshot {
            questline: 8,
            targets: 0,
            mission04: 1,
        };
        let first = target(0).ok_or(QuestRefusal::NotSupported)?;
        assert_eq!(
            first,
            SealTarget {
                position: (31964, 31203, -7),
                ordinal: 2
            }
        );
        assert!(paint_target(first, 7178, before).is_ok());
        for wrong in [
            SealTarget {
                position: (31964, 31203, -8),
                ..first
            },
            SealTarget {
                ordinal: 1,
                ..first
            },
            SealTarget {
                position: (1, 1, -7),
                ..first
            },
        ] {
            assert_eq!(
                paint_target(wrong, 7178, before),
                Err(QuestRefusal::NotSupported)
            );
        }
        for appearance in [0, 7177, 7252] {
            assert_eq!(
                paint_target(first, appearance, before),
                Err(QuestRefusal::NotSupported)
            );
        }
        assert!(target(TARGET_COUNT).is_none());
        Ok(())
    }

    #[test]
    fn distinct_source_objects_drive_the_same_three_track_planner() -> Result<(), QuestRefusal> {
        let mut state = Snapshot {
            questline: 8,
            targets: 0,
            mission04: 1,
        };
        for seal in [0, 63, 197] {
            let object = target(seal).ok_or(QuestRefusal::NotSupported)?;
            state = paint_target(object, 7178, state)?;
            assert!(paint_target(object, 7178, state).is_err());
        }
        assert_eq!((state.questline, state.mission04), (9, 2));
        assert_eq!(state.targets, 1 | (64 << 16) | (198 << 32));
        Ok(())
    }

    #[test]
    fn source_map_ids_are_unique_and_bounded() {
        let identities = SEALS
            .iter()
            .copied()
            .collect::<std::collections::BTreeSet<_>>();
        assert_eq!(identities.len(), usize::from(TARGET_COUNT));
        assert_eq!(SEALS.len(), usize::from(TARGET_COUNT));
        assert!(SEALS.iter().all(|(_, ordinal)| *ordinal < 5));
    }
}
