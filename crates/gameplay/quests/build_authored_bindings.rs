//! Compile-time registration of explicit native binding documents and their canonical evidence.
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn documents(
    directory: &Path,
    prefix: &str,
    maximum: usize,
) -> Result<Vec<PathBuf>, Box<dyn std::error::Error>> {
    println!("cargo:rerun-if-changed={}", directory.display());
    let mut paths = Vec::new();
    if directory.exists() {
        for entry in std::fs::read_dir(directory)? {
            let entry = entry?;
            let path = entry.path();
            if path
                .extension()
                .is_some_and(|extension| extension == "json")
                && path
                    .file_name()
                    .and_then(|name| name.to_str())
                    .is_some_and(|name| name.starts_with(prefix))
            {
                if !entry.file_type()?.is_file() {
                    return Err("native binding registry JSON entries must be regular files".into());
                }
                let name = path
                    .file_name()
                    .and_then(|name| name.to_str())
                    .ok_or("native binding filename")?;
                if !name.bytes().all(|byte| {
                    byte.is_ascii_lowercase() || byte.is_ascii_digit() || b"-_.".contains(&byte)
                }) {
                    return Err("native binding registry filenames must be lowercase ASCII".into());
                }
                paths.push(path);
            }
        }
    }
    paths.sort();
    if paths.len() > maximum {
        return Err("native binding registry document limit".into());
    }
    Ok(paths)
}

pub fn generate(root: &Path, out: &Path) -> Result<(), Box<dyn std::error::Error>> {
    let repository = root.join("../../..");
    let bindings = documents(
        &repository.join("content/quests/authored-bindings"),
        "",
        128,
    )?;
    let definitions = documents(
        &repository.join("content/quests/definitions"),
        "quests-",
        64,
    )?;
    let mut generated = String::from("// @generated by build_authored_bindings.rs\n");
    for (constant, paths) in [
        ("AUTHORED_BINDING_DOCUMENTS", bindings),
        ("CANONICAL_QUEST_SHARDS", definitions),
    ] {
        writeln!(
            generated,
            "pub(super) const {constant}: &[(&str, &str)] = &["
        )?;
        for path in paths {
            let path = path.canonicalize()?;
            let relative = path
                .strip_prefix(repository.canonicalize()?)?
                .to_str()
                .ok_or("native binding path")?
                .replace('\\', "/");
            let absolute = path.to_str().ok_or("native binding UTF-8 path")?;
            println!("cargo:rerun-if-changed={absolute}");
            writeln!(generated, "    ({relative:?}, include_str!({absolute:?})),")?;
        }
        generated.push_str("];\n");
    }
    std::fs::write(out.join("authored_binding_documents.rs"), generated)?;
    Ok(())
}
