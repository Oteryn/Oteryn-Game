fn roster(burning: bool) -> &'static [(u16, u16, i8, &'static str, u64)] {
    if burning {
        BURNING_SPAWNS
    } else {
        NORMAL_SPAWNS
    }
}

pub(super) fn tiles(manifest: &Manifest, phase: Option<bool>) -> &'static [PhaseTile] {
    if manifest.world.min_x > 33079
        || manifest.world.max_x <= 33104
        || manifest.world.min_y > 32143
        || manifest.world.max_y <= 32160
        || !manifest.world.floors.contains(&-7)
    {
        return &[];
    }
    match phase {
        Some(true) => BURNING_TILES,
        Some(false) => NORMAL_TILES,
        None => &[],
    }
}

pub(in crate::map) fn project_spawns(
    world: &BundleWorld,
    daily: &DailyMap,
    profile: &impl Fn(&str) -> Option<(u64, bool)>,
    sources: &mut Vec<BundleSpawnFacts>,
) -> Option<()> {
    let Some(burning) = daily.phases.get("thornfire").copied() else {
        return Some(());
    };
    if world.base().tile(33091, 32149, -7).is_none() {
        return Some(());
    }
    let owned: std::collections::BTreeSet<_> = BURNING_SPAWNS
        .iter()
        .chain(NORMAL_SPAWNS)
        .map(|&(x, y, z, creature, _)| ((i32::from(x), i32::from(y), i16::from(z)), creature))
        .collect();
    for (points, _) in &mut *sources {
        points.retain(|(point, _, creature, _, _)| !owned.contains(&(*point, creature.as_str())));
    }
    sources.retain(|(points, _)| !points.is_empty());
    for &(x, y, z, creature, respawn) in roster(burning) {
        if !world.enterable(TilePos { x, y, floor: -z }) {
            continue;
        }
        let (health, blockable) = profile(creature)?;
        sources.push((
            vec![(
                (i32::from(x), i32::from(y), i16::from(z)),
                respawn,
                creature.into(),
                health,
                blockable,
            )],
            1_000,
        ));
    }
    Some(())
}

