use super::*;

#[test]
fn registered_router_does_not_embed_the_largest_handler_future() {
    struct LargeLogout;
    impl FreshAdmissionAuthority for LargeLogout {
        async fn admit(
            &self,
            _: FreshAdmissionAttempt<'_>,
        ) -> Result<AdmittedSession, AdmissionRefusal> {
            Err(AdmissionRefusal::Unavailable)
        }

        async fn logout_command(&self, _: AdmittedSession, _: u64) -> LogoutReply {
            let retained = [0_u8; 128 * 1024];
            std::future::pending::<()>().await;
            std::hint::black_box(retained);
            LogoutReply::Unknown
        }
    }

    // Inspect the real generated route without constructing an oversized future on
    // the test stack, and without a connection, runtime or database fixture.
    fn future_size<F: std::future::Future>(
        _: impl FnOnce(
            &'static mut tokio::io::DuplexStream,
            &'static LargeLogout,
            &'static mut ServeState,
            oteryn_protocol_oteryn::ClientCommandView<'static>,
            &'static mut CommandOutcome,
        ) -> F,
    ) -> usize {
        std::mem::size_of::<F>()
    }
    let bytes = future_size(execute::<tokio::io::DuplexStream, LargeLogout>);
    assert!(bytes < 4096, "router retained handler storage: {bytes}");
}

mod generator {
    include!(concat!(env!("CARGO_MANIFEST_DIR"), "/build_mechanics.rs"));

    #[test]
    fn registry_generator_is_deterministic() {
        // Exercise the production entry point as well as the in-memory validation tests.
        // Build already ran it once: compare every generated byte to that first run. The
        // first run's bytes are embedded at compile time because a test binary run from a
        // nextest archive has no `OUT_DIR` on disk.
        const BUILT: [(&str, &[u8]); 4] = [
            (
                "mechanic_methods.rs",
                include_bytes!(concat!(env!("OUT_DIR"), "/mechanic_methods.rs")),
            ),
            (
                "mechanic_modules.rs",
                include_bytes!(concat!(env!("OUT_DIR"), "/mechanic_modules.rs")),
            ),
            (
                "mechanic_offers.rs",
                include_bytes!(concat!(env!("OUT_DIR"), "/mechanic_offers.rs")),
            ),
            (
                "mechanic_routes.rs",
                include_bytes!(concat!(env!("OUT_DIR"), "/mechanic_routes.rs")),
            ),
        ];
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
        let temp = std::env::temp_dir().join(format!(
            "oteryn-registry-determinism-{}",
            std::process::id()
        ));
        std::fs::create_dir_all(&temp).expect("registry fixture");
        generate(root, &temp).expect("registry fixture");
        for (file, built) in BUILT {
            assert_eq!(
                built,
                std::fs::read(temp.join(file))
                    .expect("registry fixture")
                    .as_slice(),
                "{file}"
            );
        }
        std::fs::remove_dir_all(temp).expect("registry fixture");
    }
}

#[test]
fn registry_routes_equal_handwritten_table_in_order() {
    let before: Vec<_> = include_str!("route_table_before.txt")
        .lines()
        .map(|line| {
            let (id, mechanic) = line.split_once(' ').expect("registry fixture");
            (id.parse::<u32>().expect("registry fixture"), mechanic)
        })
        .collect();
    let baseline_names: std::collections::BTreeSet<_> =
        before.iter().map(|(_, name)| *name).collect();
    let baseline: Vec<_> = REGISTERED_ROUTES
        .iter()
        .copied()
        .filter(|(_, name)| baseline_names.contains(name))
        .collect();
    assert_eq!(baseline, before);
}
