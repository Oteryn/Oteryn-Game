pub fn wrapped_to(source: u32) -> Option<u32> {
    let index = WRAP_TRANSFORMS.partition_point(|row| row.0 <= source);
    index.checked_sub(1).and_then(|i| {
        let row = WRAP_TRANSFORMS[i];
        (source <= row.1).then_some(row.2)
    })
}

pub fn construction_kit_to(source: u32) -> Option<u32> {
    CONSTRUCTION_KITS
        .binary_search_by_key(&source, |row| row.0)
        .ok()
        .map(|index| CONSTRUCTION_KITS[index].1)
}

